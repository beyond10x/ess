//! The same tests as a Playwright spec for the React project `ess-ui-react` generates.
//!
//! Every node is selected by `[data-ui-path="<path>"]`, the attribute the generated project
//! renders on every node, with rows scoped as `<collection>/rows/<key>/…` exactly as the test
//! file writes them. Time is Playwright's page clock, installed at zero before the page loads, so
//! `advance` and `play` run the fixture scripts the generated app plays on its own timers.
//! Replaced view fixtures and expected commands go through `page.route` on the paths the
//! generated `httpAdapter` requests (`/views/<view>`, `/commands/<command>`); a test using them
//! runs against the app with `setDataAdapter(httpAdapter(<base>))`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;
use std::time::Duration;

use ess_ui::{Body, Composite, Document, NodeRef};
use ess_ui_tui::live::Script;
use ess_ui_tui::FixtureAdapter;
use serde_yaml::Value;

use crate::spec::{Check, SectionState, Step, Test, TestFile};

/// The Playwright spec for `files`, all testing `document`.
pub fn playwright(files: &[TestFile], document: &Document) -> String {
    let mut out = String::new();
    out.push_str(
        "// Generated by `ess ui test --playwright` from ess-ui-test/1 files; do not edit.\n\
         // Nodes are selected by their canonical path, rendered as `data-ui-path`. Tests that\n\
         // replace fixtures or expect commands route /views/… and /commands/…: run the generated\n\
         // app with `setDataAdapter(httpAdapter(<base>))` for them (see its README).\n\
         import { test, expect } from \"@playwright/test\";\n",
    );
    for file in files {
        let loaded = fixtured(file, document);
        let name = file
            .source
            .file_name()
            .map_or_else(String::new, |name| name.to_string_lossy().into_owned());
        let _ = write!(out, "\ntest.describe({}, () => {{\n", string(&name));
        for (index, test) in file.tests.iter().enumerate() {
            if index > 0 {
                out.push('\n');
            }
            emit_test(&mut out, test, document, &loaded);
        }
        out.push_str("});\n");
    }
    out
}

/// What a file's tests read of the document's fixtures: its channel scripts and its derived views
/// (`same_as`, `by_id_from`), when they load.
struct Fixtured {
    scripts: Vec<Script>,
    derived: BTreeMap<String, Value>,
}

fn fixtured(file: &TestFile, document: &Document) -> Fixtured {
    let named = file
        .source
        .parent()
        .unwrap_or(Path::new(""))
        .join(&file.document);
    let base = named.parent().unwrap_or(Path::new(""));
    let scripts = FixtureAdapter::load(document, base, None)
        .map(|(_, scripts)| scripts)
        .unwrap_or_default();
    let mut derived = BTreeMap::new();
    if let Some(index) = &document.fixtures {
        derived.extend(index.derived.clone());
        let listed = index
            .index
            .as_ref()
            .and_then(|file| std::fs::read_to_string(base.join(file)).ok())
            .and_then(|text| serde_yaml::from_str::<ess_ui::FixtureIndex>(&text).ok());
        if let Some(listed) = listed {
            derived.extend(listed.derived);
        }
    }
    Fixtured { scripts, derived }
}

/// A derived view answered from a view the test replaces: the replaced view, and the `by_id_from`
/// keys the rows are narrowed by on the way, as the terminal's fixture adapter resolves it.
fn derived_from<'t>(
    view: &str,
    derived: &BTreeMap<String, Value>,
    replaced: &'t BTreeMap<String, Value>,
) -> Option<(&'t Value, Vec<String>)> {
    let mut current = view.to_owned();
    let mut keys = Vec::new();
    // The adapter gives up after eight hops.
    for _ in 0..=8 {
        let rule = derived.get(&current)?;
        if let Some(source) = rule.get("same_as").and_then(Value::as_str) {
            current = source.to_owned();
        } else {
            let source = rule.get("by_id_from").and_then(Value::as_str)?;
            keys.push(
                rule.get("key")
                    .and_then(Value::as_str)
                    .unwrap_or("id")
                    .to_owned(),
            );
            current = source.to_owned();
        }
        if let Some(data) = replaced.get(&current) {
            return Some((data, keys));
        }
    }
    None
}

/// A `page.route` matcher for exactly `/views/<view>`, not every view the name prefixes.
fn view_route(view: &str) -> String {
    format!(
        "(url) => url.pathname.endsWith({})",
        string(&format!("/views/{view}"))
    )
}

fn emit_test(out: &mut String, test: &Test, document: &Document, fixtured: &Fixtured) {
    let _ = writeln!(
        out,
        "  test({}, async ({{ page }}) => {{",
        string(&test.name)
    );
    let line = |out: &mut String, text: &str| {
        let _ = writeln!(out, "    {text}");
    };
    let mut scripts = fixtured.scripts.clone();
    for (channel, value) in &test.fixtures.scripts {
        if let Ok(script) = Script::parse(channel, value) {
            scripts.retain(|known| known.channel != script.channel);
            scripts.push(script);
        }
        line(
            out,
            &format!(
                "test.fixme(true, {});",
                string(&format!(
                    "replaces the {channel} script; the generated app plays its own fixture scripts"
                ))
            ),
        );
    }
    if !test.latency.is_zero() {
        line(
            out,
            &format!(
                "// latency {}ms: the generated fixture adapter answers after its own delay.",
                test.latency.as_millis()
            ),
        );
    }
    if test
        .steps
        .iter()
        .any(|step| matches!(step, Step::ExpectCommand { .. }))
    {
        line(
            out,
            "const commands: { command: string; input: unknown }[] = [];",
        );
        line(
            out,
            "await page.route(\"**/commands/**\", async (route) => {",
        );
        line(out, "  const url = new URL(route.request().url());");
        line(
            out,
            "  commands.push({ command: decodeURIComponent(url.pathname.split(\"/commands/\")[1] ?? \"\"), input: route.request().postDataJSON() });",
        );
        line(out, "  await route.fulfill({ json: { accepted: true } });");
        line(out, "});");
    }
    for (view, data) in &test.fixtures.views {
        line(
            out,
            &format!(
                "await page.route({}, (route) => route.fulfill({{ json: {} }}));",
                view_route(view),
                json(data)
            ),
        );
    }
    // Views derived from a replaced view follow it, as they do in the terminal.
    for view in fixtured.derived.keys() {
        if test.fixtures.views.contains_key(view) {
            continue;
        }
        let Some((data, keys)) = derived_from(view, &fixtured.derived, &test.fixtures.views) else {
            continue;
        };
        if keys.is_empty() {
            line(
                out,
                &format!(
                    "await page.route({}, (route) => route.fulfill({{ json: {} }}));",
                    view_route(view),
                    json(data)
                ),
            );
            continue;
        }
        line(
            out,
            &format!(
                "await page.route({}, (route) => {{ const params = JSON.parse(new URL(route.request().url()).searchParams.get(\"params\") ?? \"{{}}\"); const source = {}; const rows = (Array.isArray(source) ? source : source.rows ?? []).filter((row) => {}.every((key) => String(row[key]) === String(params[key] ?? params.id))); return route.fulfill({{ json: {{ rows }} }}); }});",
                view_route(view),
                json(data),
                json(&keys)
            ),
        );
    }
    line(out, "await page.clock.install({ time: 0 });");
    let mut now = Duration::ZERO;
    for step in &test.steps {
        let lines = match refusal(step, document) {
            Some(reason) => vec![fixme(&reason)],
            None => emit_step(step, document, &scripts, &mut now),
        };
        let refused = lines.iter().any(|text| text.starts_with("test.fixme("));
        for text in lines {
            line(out, &text);
        }
        // `test.fixme` ends the test where it stands, as the terminal's refusal ends its run.
        if refused {
            break;
        }
    }
    out.push_str("  });\n");
}

/// `test.fixme(true, "<reason>");`: the test stops here, reported as not yet meaningful.
fn fixme(reason: &str) -> String {
    format!("test.fixme(true, {});", string(reason))
}

/// Why the terminal refuses `step` because the renderers draw its node differently
/// ([`crate::parity`]), if it does. A path that names no node is not a refusal: both renderers
/// fail it.
fn refusal(step: &Step, document: &Document) -> Option<String> {
    let (at, checks) = match step {
        Step::Select { at }
        | Step::Type { at, .. }
        | Step::Choose { at, .. }
        | Step::Act { at }
        | Step::Page { at, .. } => (at, None),
        Step::Expect { at, checks } => (at, Some(checks)),
        Step::Open { .. } | Step::Play(_) | Step::Advance(_) | Step::ExpectCommand { .. } => {
            return None
        }
    };
    let target = crate::target::resolve(document, at).ok()?;
    if let Some(reason) = crate::parity::unrendered(document, &target) {
        return Some(reason);
    }
    if let Some(reason) = crate::parity::undriven(document, &target) {
        return Some(reason);
    }
    if matches!(step, Step::Choose { .. }) {
        return crate::parity::choose(document, &target);
    }
    checks?
        .iter()
        .filter(|check| matches!(check, Check::Text(_) | Check::NotText(_)))
        .find_map(|_| crate::parity::text(document, &target))
}

#[allow(clippy::too_many_lines)] // one arm per step
fn emit_step(
    step: &Step,
    document: &Document,
    scripts: &[Script],
    now: &mut Duration,
) -> Vec<String> {
    let refuse = |reason: String| vec![fixme(&reason)];
    match step {
        Step::Open { page, params } => {
            let Some(definition) = document.pages.get(page) else {
                return refuse(format!("open {page}: the document has no such page"));
            };
            let mut route = ess_ui_react::route_pattern(page, definition);
            for (name, value) in params {
                route = route.replace(&format!(":{name}"), value);
            }
            vec![format!("await page.goto({});", string(&route))]
        }
        Step::Select { at } => {
            if at.split('/').count() == 2 {
                return vec!["await page.keyboard.press(\"Escape\");".to_owned()];
            }
            if let Some((container, row)) = row_of(at) {
                return select_row(document, &container, &row);
            }
            vec![format!("await {}.scrollIntoViewIfNeeded();", locator(at))]
        }
        Step::Type { at, text } => match node_kind(document, at) {
            Kind::FilterBar => vec![format!(
                "await page.locator('{} input[type=\"search\"]').pressSequentially({});",
                selector(at),
                string(text)
            )],
            Kind::Field => vec![format!(
                "await page.locator('{0} input, {0} textarea').first().pressSequentially({1});",
                selector(at),
                string(text)
            )],
            _ => refuse(format!(
                "type at {at}: the generated app has no text input there"
            )),
        },
        Step::Choose { at, option } => {
            let (label, buttons) = choice(document, at, option);
            if buttons {
                vec![format!(
                    "await {}.getByRole(\"button\", {{ name: {}, exact: true }}).click();",
                    locator(at),
                    string(&label)
                )]
            } else {
                vec![format!(
                    "await {}.locator(\"select\").selectOption({{ label: {} }});",
                    locator(at),
                    string(&label)
                )]
            }
        }
        Step::Act { at } => {
            if node_kind(document, at) == Kind::Overlay {
                let at = selector(at);
                return vec![format!(
                    "await page.locator('{at} button.ui-tone-danger, {at} button.ui-tone-primary').last().click();"
                )];
            }
            vec![format!("await {}.click();", locator(at))]
        }
        Step::Page { at, to } => {
            // `to` is absolute: back to page 1 from wherever the pager is, then forward. Each click
            // waits for the pager to show the page it leads to.
            let pager = format!("page.locator('{} .ui-pager')", selector(at));
            let mut lines = vec![
                format!("// page {to} of {at}"),
                format!(
                    "for (let shown = (await {pager}.count()) > 0 ? Number((await {pager}.locator(\"span\").textContent())?.replace(/\\D/g, \"\")) : 1; shown > 1; shown -= 1) {{ await {pager}.locator(\"button\").first().click(); await expect({pager}.locator(\"span\")).toHaveText(`Page ${{shown - 1}}`); }}"
                ),
            ];
            for page in 2..=*to {
                lines.push(format!("await {pager}.locator(\"button\").last().click();"));
                lines.push(format!(
                    "await expect({pager}.locator(\"span\")).toHaveText({});",
                    string(&format!("Page {page}"))
                ));
            }
            lines
        }
        Step::Expect { at, checks } => checks
            .iter()
            .flat_map(|check| emit_check(at, check))
            .collect(),
        Step::Play(play) => match crate::clock::next(scripts, play, *now) {
            Some(at) => {
                let by = at.saturating_sub(*now);
                match crate::clock::advance(scripts, *now, by) {
                    Ok(moved) => *now = moved,
                    Err(reason) => return refuse(reason),
                }
                vec![
                    format!("// play {play}: at {}ms", at.as_millis()),
                    format!("await page.clock.runFor({});", by.as_millis()),
                ]
            }
            None => refuse(format!("play {play}: the fixture scripts do not play it")),
        },
        Step::Advance(by) => {
            match crate::clock::advance(scripts, *now, *by) {
                Ok(moved) => *now = moved,
                Err(reason) => return refuse(reason),
            }
            vec![format!("await page.clock.runFor({});", by.as_millis())]
        }
        Step::ExpectCommand { command, input } => {
            if input.is_empty() {
                return vec![format!(
                    "expect(commands.map((sent) => sent.command)).toContain({});",
                    string(command)
                )];
            }
            vec![format!(
                "expect(commands).toContainEqual(expect.objectContaining({{ command: {}, input: {} }}));",
                string(command),
                input_matcher(input)
            )]
        }
    }
}

/// The matcher an expected command input is held to, as the terminal holds it: JSON values with
/// their types, an object by the fields it names (`expect.objectContaining`), a list item by item,
/// and a dotted field name as nested objects.
fn input_matcher(input: &BTreeMap<String, Value>) -> String {
    let mut nested = serde_yaml::Mapping::new();
    for (field, value) in input {
        let mut segments: Vec<&str> = field.split('.').collect();
        let last = segments.pop().unwrap_or_default();
        let mut at = &mut nested;
        for segment in segments {
            let key = Value::String(segment.to_owned());
            if !at.get(&key).is_some_and(Value::is_mapping) {
                at.insert(key.clone(), Value::Mapping(serde_yaml::Mapping::new()));
            }
            let Some(Value::Mapping(inner)) = at.get_mut(&key) else {
                unreachable!("inserted above")
            };
            at = inner;
        }
        at.insert(Value::String(last.to_owned()), value.clone());
    }
    matcher(&Value::Mapping(nested))
}

fn matcher(value: &Value) -> String {
    match value {
        Value::Mapping(fields) => {
            let fields: Vec<String> = fields
                .iter()
                .map(|(name, value)| {
                    format!("{}:{}", string(&crate::spec::scalar(name)), matcher(value))
                })
                .collect();
            format!("expect.objectContaining({{{}}})", fields.join(","))
        }
        Value::Sequence(items) => format!(
            "[{}]",
            items.iter().map(matcher).collect::<Vec<_>>().join(",")
        ),
        Value::Tagged(tagged) => matcher(&tagged.value),
        other => json(other),
    }
}

fn emit_check(at: &str, check: &Check) -> Vec<String> {
    let rows = format!("page.locator('{} .ui-row')", selector(at));
    let status = |status: &str| {
        format!(
            "await expect({}).toHaveAttribute(\"data-status\", {});",
            locator(at),
            string(status)
        )
    };
    // A number of four or more digits matches with or without grouping, as in the terminal.
    let expected = |text: &str| {
        crate::numbers::pattern(text).map_or_else(
            || string(text),
            |pattern| format!("new RegExp({})", string(&pattern)),
        )
    };
    match check {
        Check::Text(text) => vec![format!(
            "await expect({}).toContainText({});",
            locator(at),
            expected(text)
        )],
        Check::NotText(text) => vec![format!(
            "await expect({}).not.toContainText({});",
            locator(at),
            expected(text)
        )],
        Check::RowCount(count) => vec![format!("await expect({rows}).toHaveCount({count});")],
        Check::RowKeys(keys) => {
            let mut lines = vec![format!("await expect({rows}).toHaveCount({});", keys.len())];
            for (index, key) in keys.iter().enumerate() {
                lines.push(format!(
                    "await expect({rows}.nth({index})).toHaveAttribute(\"data-ui-path\", {});",
                    string(&format!("{at}/rows/{key}"))
                ));
            }
            lines
        }
        Check::State(state) => match state {
            SectionState::Loading => vec![status("loading")],
            SectionState::Failed => vec![status("failed")],
            SectionState::Ready => vec![status("ready")],
            SectionState::NotLoaded => vec![status("idle")],
            SectionState::Empty => vec![
                status("ready"),
                format!("await expect({rows}).toHaveCount(0);"),
            ],
            SectionState::Stale => vec![format!(
                "await expect(page.locator('{} .ui-stale-badge')).toBeVisible();",
                selector(at)
            )],
        },
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    FilterBar,
    Field,
    Overlay,
    Other,
}

fn node_kind(document: &Document, at: &str) -> Kind {
    let unscoped = unscope(at);
    document
        .nodes()
        .into_iter()
        .find(|located| located.path.to_string() == unscoped)
        .map_or(Kind::Other, |located| match located.node {
            NodeRef::Section(section)
                if matches!(section.body, Body::Composite(Composite::FilterBar(_))) =>
            {
                Kind::FilterBar
            }
            NodeRef::Field(_) => Kind::Field,
            NodeRef::Overlay(_) => Kind::Overlay,
            _ => Kind::Other,
        })
}

/// The collection and the row path of a path inside a row: `<collection>/rows/<key>/…`.
fn row_of(at: &str) -> Option<(String, String)> {
    let segments: Vec<&str> = at.split('/').collect();
    let index = segments.iter().position(|segment| *segment == "rows")?;
    let key = segments.get(index + 1)?;
    let container = segments[..index].join("/");
    Some((container.clone(), format!("{container}/rows/{key}")))
}

/// `select` of a row: what the terminal's cursor does, without activating anything in the row.
///
/// The terminal moves its cursor to the row; the generated app's counterpart is the focused row
/// (`ui-focused`), set by the row's own click handler. A pointer click lands on the row's centre,
/// which can be a link or a button inside a cell and navigate, so the click is dispatched on the
/// row element itself and the focus is then checked. A collection with an `expand` also expands
/// the row it focuses in the generated app, which the terminal's cursor does not: such a step
/// is `test.fixme`.
fn select_row(document: &Document, container: &str, row: &str) -> Vec<String> {
    let expands = document.nodes().into_iter().any(|located| {
        let body = match located.node {
            NodeRef::Section(section) => &section.body,
            NodeRef::Node(node) => &node.body,
            NodeRef::Overlay(overlay) => &overlay.body,
            _ => return false,
        };
        located.path.to_string() == container
            && matches!(body, Body::Composite(Composite::Collection(collection)) if collection.expand.is_some())
    });
    if expands {
        return vec![format!(
            "test.fixme(true, {});",
            string(&format!(
                "select {row}: focusing a row of this collection in the generated app also expands it"
            ))
        )];
    }
    vec![
        format!("await {}.dispatchEvent(\"click\");", locator(row)),
        format!(
            "await expect({}).toHaveClass(/(^|\\s)ui-focused(\\s|$)/);",
            locator(row)
        ),
    ]
}

/// A path with its row scope (`rows/<key>`) removed.
fn unscope(at: &str) -> String {
    let segments: Vec<&str> = at.split('/').collect();
    match segments.iter().position(|segment| *segment == "rows") {
        Some(index) if index + 1 < segments.len() => segments[..index]
            .iter()
            .chain(&segments[index + 2..])
            .copied()
            .collect::<Vec<_>>()
            .join("/"),
        _ => at.to_owned(),
    }
}

/// The label an option shows and whether the choice renders as buttons.
fn choice(document: &Document, at: &str, option: &str) -> (String, bool) {
    let found = document
        .nodes()
        .into_iter()
        .find_map(|located| match located.node {
            NodeRef::Node(node) if located.path.to_string() == at => match &node.body {
                Body::Composite(Composite::Choice(choice)) => Some(choice.clone()),
                _ => None,
            },
            // A form's choice field: its `choice` node draws the control inside the field.
            NodeRef::Field(field) if located.path.to_string() == at => {
                match field.choice.as_ref().map(|node| &node.body) {
                    Some(Body::Composite(Composite::Choice(choice))) => Some(choice.clone()),
                    _ => None,
                }
            }
            _ => None,
        });
    let Some(choice) = found else {
        return (option.to_owned(), true);
    };
    let label = choice
        .options
        .iter()
        .find(|known| crate::spec::scalar(&known.value) == option || known.label == option)
        .map_or_else(|| option.to_owned(), |known| known.label.clone());
    let style = choice
        .style
        .as_ref()
        .map(|style| format!("{style:?}").to_lowercase());
    let buttons = matches!(
        style.as_deref(),
        Some("segmented" | "tags" | "checklist" | "radio")
    ) || (choice.multiple && style.as_deref() != Some("dropdown"));
    (label, buttons)
}

/// `[data-ui-path="<path>"]`, safe inside a single-quoted TypeScript string.
fn selector(path: &str) -> String {
    let escaped = path
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\'', "\\'");
    format!("[data-ui-path=\"{escaped}\"]")
}

fn locator(path: &str) -> String {
    format!("page.locator('{}')", selector(path))
}

/// A TypeScript string literal.
fn string(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| "\"\"".to_owned())
}

fn json<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "null".to_owned())
}
