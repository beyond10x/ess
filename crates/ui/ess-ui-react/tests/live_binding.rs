/// `examples/gatepass` as `(label, text)` sources, with `extra_views` appended to its one domain
/// (whose last key is `views:`).
fn gatepass_with(extra_views: &str) -> Vec<(String, String)> {
    let root = root().join("examples/gatepass");
    let mut visit = read(&root.join("domains/visit.yaml"));
    visit.push_str(extra_views);
    vec![
        ("system.yaml".to_owned(), read(&root.join("system.yaml"))),
        (
            "components.yaml".to_owned(),
            read(&root.join("components.yaml")),
        ),
        ("domains/visit.yaml".to_owned(), visit),
    ]
}

fn load(text: &str) -> Document {
    ess_ui::load_str(text).unwrap_or_else(|error| panic!("the document loads: {error}"))
}

fn bind(document: &Document, sources: &[(String, String)]) -> Binding {
    ess_ui_check::binding(document, sources)
        .unwrap_or_else(|error| panic!("the document binds: {error}"))
}

/// The desk, bound to gatepass, generated under `name`.
fn bound_desk(name: &str) -> (PathBuf, GeneratedFiles, Binding) {
    let document = load(DESK);
    let binding = bind(&document, &gatepass_with(""));
    let out = scratch(name);
    let files = ess_ui_react::generate_bound(&document, &root(), &out, Some(&binding))
        .unwrap_or_else(|error| panic!("{error}"));
    (out, files, binding)
}

fn file<'a>(files: &'a GeneratedFiles, path: &str) -> &'a str {
    files
        .files
        .get(path)
        .unwrap_or_else(|| panic!("`{path}` is generated; have {:?}", files.files.keys()))
}

/// FNV-1a, 64 bits: a digest of generated bytes that needs no dependency.
fn fnv(text: &str) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in text.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash
}

