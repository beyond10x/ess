#[test]
fn without_a_model_the_project_is_byte_identical() {
    let document = load(DESK);
    let plain = ess_ui_react::render(&document, &root()).unwrap_or_else(|error| panic!("{error}"));
    let unbound = ess_ui_react::render_bound(&document, &root(), None)
        .unwrap_or_else(|error| panic!("{error}"));
    assert_eq!(plain, unbound, "render is render_bound without a binding");
    for (path, digest) in PLAIN {
        assert_eq!(
            fnv(file(&plain, path)),
            digest,
            "{path} differs from the consolidated unbound projection:\n{}",
            file(&plain, path)
        );
    }
    let mut whole = String::new();
    for (path, text) in &plain.files {
        whole.push_str(path);
        whole.push('\0');
        whole.push_str(text);
        whole.push('\0');
    }
    assert_eq!(
        fnv(&whole),
        PLAIN_PROJECT,
        "the project differs from the consolidated unbound projection: {:?}",
        plain.files.keys()
    );
    for absent in ["src/binding.ts", "src/runtime/answer.ts"] {
        assert!(!plain.files.contains_key(absent), "{absent} is generated");
    }
}

#[test]
fn binding_ts_holds_the_served_paths_and_query_wire_names() {
    // A view whose parameter is carried under another query key than its name.
    let sources = gatepass_with(
        "\n  - name: gatepass.visit.InBuilding\n    source: gatepass.visit.Visit\n    \
         consistency: eventual\n    params:\n      - name: building\n        type: \
         gatepass.visit.Building\n        naming: {wire: site}\n    filter: building == \
         param.building\n    fields:\n      - name: visit_id\n        type: \
         gatepass.visit.VisitId\n",
    );
    let text = DESK.replace(
        "      - name: register\n",
        "      - name: here\n        component: collection\n        \
         reads: {view: visit.InBuilding, params: {building: \"'North'\"}}\n      \
         - name: register\n",
    );
    let document = load(&text);
    let binding = bind(&document, &sources);
    let files = ess_ui_react::render_bound(&document, &root(), Some(&binding))
        .unwrap_or_else(|error| panic!("{error}"));
    let ts = file(&files, "src/binding.ts");
    for wanted in [
        "\"/visits/views/expected\"",
        "\"/visits/commands/register-visit\"",
        "\"/visits/commands/admit-visitor\"",
        "\"/visits/commands/sign-out-visitor\"",
        "\"wire\": \"site\"",
        "\"visit.RegisterVisit\": \"gatepass.visit.RegisterVisit\"",
    ] {
        assert!(ts.contains(wanted), "binding.ts lacks {wanted}:\n{ts}");
    }
    // The binding as data: the object literal is the binding's JSON, member for member.
    let literal = ts
        .split_once("export const binding: Binding = ")
        .and_then(|(_, rest)| rest.trim_end().strip_suffix(';'))
        .unwrap_or_else(|| panic!("binding.ts exports no binding literal:\n{ts}"));
    let parsed: serde_json::Value =
        serde_json::from_str(literal).unwrap_or_else(|error| panic!("{error}:\n{literal}"));
    assert_eq!(
        parsed,
        serde_json::to_value(&binding).expect("the binding serialises")
    );
    // The adapter it drives, switched on before the app renders, and a base URL per component.
    let main = file(&files, "src/main.tsx");
    assert!(
        main.contains("setDataAdapter(httpAdapter(binding));"),
        "{main}"
    );
    let html = file(&files, "www/index.html");
    assert!(
        html.contains("<meta name=\"ess-base-url:pass-service\" content=\"\" />"),
        "{html}"
    );
    // Deterministic.
    let again = ess_ui_react::render_bound(&document, &root(), Some(&binding))
        .unwrap_or_else(|error| panic!("{error}"));
    assert_eq!(files, again);
}

