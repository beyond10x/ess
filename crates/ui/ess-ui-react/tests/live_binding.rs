//! The generated React app bound to a served surface (beyond10x/ess#311, S2): with a binding from
//! `ess_ui_check::binding`, the project carries `src/binding.ts` and an `httpAdapter` that reads
//! and commands the paths the synthesized server answers, classifies every command answer with a
//! port of `ess_ui::binding::classify`, and shows a refusal on the form, confirm or action that
//! sent it. Without a binding the project is the plain one, byte for byte.
//!
//! Runtime cases compile the generated project to `CommonJS` with `tsc` and run it under `node`
//! against the stand-ins in `support`; the end-to-end case also builds it with esbuild and drives
//! it against the Rust gatepass server from `examples/gatepass-realization`.

