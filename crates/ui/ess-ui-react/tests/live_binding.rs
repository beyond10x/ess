/// Runs the project's own `build` script (`tsc --noEmit && esbuild …`) against stand-in `react`
/// and `react-dom` packages typed by the project's offline declarations.
fn build(project: &Path) {
    let modules = project.join("node_modules");
    let types = |file: &str| read(&project.join("types").join(file));
    write(
        &modules.join("react/package.json"),
        r#"{"name":"react","main":"index.js","types":"index.d.ts"}"#,
    );
    write(&modules.join("react/index.js"), REACT);
    write(&modules.join("react/index.d.ts"), &types("react.d.ts"));
    write(
        &modules.join("react/jsx-runtime.js"),
        "\"use strict\";\nconst jsx = (type, props) => ({ type, props });\nmodule.exports = { jsx, jsxs: jsx };\n",
    );
    write(
        &modules.join("react/jsx-runtime.d.ts"),
        &types("react-jsx-runtime.d.ts"),
    );
    write(
        &modules.join("react-dom/package.json"),
        r#"{"name":"react-dom","main":"client.js"}"#,
    );
    write(
        &modules.join("react-dom/client.js"),
        "\"use strict\";\nexports.createRoot = () => ({ render() {}, unmount() {} });\n",
    );
    write(
        &modules.join("react-dom/client.d.ts"),
        &types("react-dom-client.d.ts"),
    );
    let package: serde_json::Value =
        serde_json::from_str(&read(&project.join("package.json"))).expect("package.json parses");
    let script = package["scripts"]["build"]
        .as_str()
        .expect("a build script");
    let output = Command::new("sh")
        .args(["-c", script])
        .current_dir(project)
        .output()
        .expect("sh runs");
    assert!(
        output.status.success(),
        "`{script}` failed:\n{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    let bundle = read(&project.join("www/assets/main.js"));
    assert!(
        bundle.contains("/visits/commands/register-visit"),
        "the bundle carries no binding"
    );
}

