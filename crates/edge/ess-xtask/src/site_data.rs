#[derive(Serialize)]
struct Terminal {
    format: &'static str,
    title: &'static str,
    entries: Vec<Entry>,
    #[serde(rename = "recordedWith")]
    recorded_with: &'static str,
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    tones: BTreeMap<String, &'static str>,
}

#[derive(Serialize)]
struct Entry {
    command: String,
    output: String,
    #[serde(rename = "exitCode")]
    exit_code: i32,
}

/// Writes, or with `check` compares, every file under [`DATA`].
pub(super) fn run(root: &Path, check: bool, ess: Option<&Path>) -> Result<String> {
    let ess = match ess {
        Some(path) => path.to_path_buf(),
        None => build_ess(root)?,
    };
    let files = render(root, &ess)?;
    let directory = root.join(DATA);
    let mut report = String::new();
    let mut stale = Vec::new();
    for (name, contents) in &files {
        let path = directory.join(name);
        let current = fs::read_to_string(&path).ok();
        if current.as_deref() == Some(contents.as_str()) {
            continue;
        }
        if check {
            stale.push(format!("{DATA}/{name}"));
        } else {
            fs::create_dir_all(&directory).with_context(|| format!("creating {DATA}"))?;
            fs::write(&path, contents).with_context(|| format!("writing {DATA}/{name}"))?;
            writeln!(report, "{DATA}/{name}: regenerated")?;
        }
    }
    let page_path = root.join(STATUS_PAGE);
    let page = fs::read_to_string(&page_path).with_context(|| format!("reading {STATUS_PAGE}"))?;
    let record = fs::read_to_string(root.join(STATUS_RECORD))
        .with_context(|| format!("reading {STATUS_RECORD}"))?;
    let rendered = status_page(&page, &status_tables(&record, &root.join("website/docs"))?)
        .with_context(|| format!("rendering {STATUS_RECORD} into {STATUS_PAGE}"))?;
    if rendered != page {
        if check {
            stale.push(STATUS_PAGE.to_owned());
        } else {
            fs::write(&page_path, rendered).with_context(|| format!("writing {STATUS_PAGE}"))?;
            writeln!(report, "{STATUS_PAGE}: status record regenerated")?;
        }
    }
    if !stale.is_empty() {
        bail!(
            "these files differ from a fresh recording of `ess`: {}. Run `cargo xtask site-data` \
             and commit the result; never edit them by hand.",
            stale.join(", ")
        );
    }
    if report.is_empty() {
        report = format!(
            "{DATA}: {} file(s) agree with a fresh recording of `ess`\n",
            files.len()
        );
    }
    Ok(report)
}

/// Builds the `ess` binary from this workspace and returns its path.
fn build_ess(root: &Path) -> Result<PathBuf> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let output = std::process::Command::new(&cargo)
        .args([
            "build",
            "--quiet",
            "--locked",
            "--offline",
            "--package",
            "ess-cli",
            "--bin",
            "ess",
            "--message-format",
            "json",
        ])
        .current_dir(root)
        .stderr(Stdio::inherit())
        .output()
        .with_context(|| format!("running {cargo:?} build for ess"))?;
    ensure!(output.status.success(), "building `ess` failed");
    for line in String::from_utf8_lossy(&output.stdout).lines() {
        let Ok(message) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        if message["reason"] == "compiler-artifact" && message["target"]["name"] == "ess" {
            if let Some(executable) = message["executable"].as_str() {
                return Ok(PathBuf::from(executable));
            }
        }
    }
    bail!("`cargo build` reported no `ess` executable")
}

/// Every generated file, keyed by its name under [`DATA`].
fn render(root: &Path, ess: &Path) -> Result<BTreeMap<String, String>> {
    let scratch = Scratch::new()?;
    copy_tree(&root.join(EXAMPLE), &scratch.0.join(EXAMPLE))?;
    let mut files = BTreeMap::new();
    for session in SESSIONS {
        let mut entries = Vec::new();
        for step in session.steps {
            entries.push(record(ess, &scratch.0, step)?);
        }
        let tones = tones(entries.iter().map(|entry| entry.output.as_str()));
        let document = Terminal {
            format: "b10x-terminal/1",
            title: session.title,
            entries,
            recorded_with: RECORDED_WITH,
            tones,
        };
        files.insert(session.file.to_owned(), pretty(&document)?);
    }
    let compiled = std::process::Command::new(ess)
        .args(["specify", "compile", "--path", EXAMPLE, "--format", "json"])
        .current_dir(&scratch.0)
        .output()
        .with_context(|| format!("running {}", ess.display()))?;
    ensure!(
        compiled.status.success(),
        "`ess specify compile` refused the example: {}",
        String::from_utf8_lossy(&compiled.stderr)
    );
    let model: Value =
        serde_json::from_slice(&compiled.stdout).context("reading the compiled model")?;
    for graph in domain_graphs(&model)? {
        let name = format!("{}.domain-graph.json", graph.domain.id.replace('.', "-"));
        files.insert(name, pretty(&graph)?);
    }
    files.insert(PAIR_FILE.to_owned(), pretty(&code_pair(ess, &scratch.0)?)?);
    Ok(files)
}

#[derive(Serialize)]
struct CodePair {
    format: &'static str,
    from: Pane,
    to: Pane,
    via: String,
    #[serde(rename = "recordedWith")]
    recorded_with: &'static str,
}

#[derive(Serialize)]
struct Pane {
    title: String,
    language: &'static str,
    code: String,
}

/// [`PAIR_TYPE`] as the example declares it and as `ess generate --kind openapi` projects it, both
/// quoted verbatim from the files: the declaration from the example's source, the schema from a
/// fresh projection into the scratch directory.
fn code_pair(ess: &Path, scratch: &Path) -> Result<CodePair> {
    let args = [
        "generate", "generate", "--path", EXAMPLE, "--kind", "openapi", "--out", PAIR_OUT,
    ];
    let output = std::process::Command::new(ess)
        .args(args)
        .current_dir(scratch)
        .output()
        .with_context(|| format!("running {}", ess.display()))?;
    ensure!(
        output.status.success(),
        "`ess {}` failed: {}",
        args.join(" "),
        String::from_utf8_lossy(&output.stderr)
    );
    let source_path = format!("{EXAMPLE}/{PAIR_SOURCE}");
    let projection_path = format!("{PAIR_OUT}/{PAIR_PROJECTION}");
    let read = |path: &str| {
        fs::read_to_string(scratch.join(path)).with_context(|| format!("reading {path}"))
    };
    let declaration = excerpt(&read(&source_path)?, &format!("  - name: {PAIR_TYPE}"))
        .with_context(|| format!("quoting {PAIR_TYPE} from {source_path}"))?;
    let schema = excerpt(&read(&projection_path)?, &format!("    {PAIR_TYPE}:"))
        .with_context(|| format!("quoting {PAIR_TYPE} from {projection_path}"))?;
    Ok(CodePair {
        format: "b10x-code-pair/1",
        from: Pane {
            title: source_path,
            language: "yaml",
            code: declaration,
        },
        to: Pane {
            title: projection_path,
            language: "yaml",
            code: schema,
        },
        via: "ess generate generate --kind openapi".to_owned(),
        recorded_with: RECORDED_WITH,
    })
}

/// The YAML block that opens with the one line equal to `head`: that line and every following
/// line indented deeper than it, up to the first blank line, without whole-line comments (a hero
/// pane is narrow, and the comment is the source's widest line). Refuses a head that is missing or
/// appears twice, so a renamed type fails the check instead of quoting something else.
fn excerpt(document: &str, head: &str) -> Result<String> {
    let lines: Vec<&str> = document.lines().collect();
    let starts: Vec<usize> = lines
        .iter()
        .enumerate()
        .filter(|(_, line)| **line == head)
        .map(|(index, _)| index)
        .collect();
    let [start] = starts[..] else {
        bail!("expected exactly one line `{head}`, found {}", starts.len());
    };
    let indent = |line: &str| line.len() - line.trim_start().len();
    let mut block = vec![lines[start]];
    for line in &lines[start + 1..] {
        if line.trim().is_empty() || indent(line) <= indent(head) {
            break;
        }
        if !line.trim_start().starts_with('#') {
            block.push(line);
        }
    }
    Ok(block.join("\n") + "\n")
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct StatusRecord {
    format: String,
    #[serde(rename = "asOf")]
    as_of: Option<String>,
    #[allow(dead_code)]
    source: Option<String>,
    items: Vec<StatusItem>,
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct StatusItem {
    label: String,
    status: String,
    detail: Option<String>,
    href: Option<String>,
    area: Option<String>,
}

/// The status record as Markdown: one list per `area`, in the order areas first appear. Each item
/// opens with its status as inline code, which the product site turns into a status chip, and
/// links its documentation page by a path relative to the status page so that both the product
/// site and the collected documentation resolve it. A list rather than a table, because three
/// columns leave the detail a word wide on a phone. A link to a page that does not exist is
/// refused rather than written.
fn status_tables(record: &str, docs: &Path) -> Result<String> {
    let record: StatusRecord = serde_json::from_str(record).context("reading the status record")?;
    ensure!(
        record.format == "b10x-status/1",
        "the status record's format is {}, not b10x-status/1",
        record.format
    );
    let mut areas: Vec<(&str, Vec<&StatusItem>)> = Vec::new();
    let mut labels = BTreeSet::new();
    for item in &record.items {
        ensure!(
            labels.insert(&item.label),
            "status label `{}` appears twice",
            item.label
        );
        ensure!(
            ["shipped", "decided", "planned"].contains(&item.status.as_str()),
            "status `{}` of `{}` is not shipped, decided or planned",
            item.status,
            item.label
        );
        let area = item.area.as_deref().unwrap_or("Other");
        match areas.iter_mut().find(|(name, _)| *name == area) {
            Some((_, items)) => items.push(item),
            None => areas.push((area, vec![item])),
        }
    }
    let mut out = String::new();
    if let Some(as_of) = &record.as_of {
        writeln!(
            out,
            "Generated from `{STATUS_RECORD}`, the file the landing page's status section reads; \
             statuses as of {as_of}."
        )?;
        out.push('\n');
    }
    for (area, items) in areas {
        writeln!(out, "### {area}\n")?;
        for item in items {
            let label = match &item.href {
                Some(href) => format!("[{}]({})", item.label, relative_doc(href, docs)?),
                None => item.label.clone(),
            };
            let detail = item
                .detail
                .as_deref()
                .map(|detail| format!(" — {detail}"))
                .unwrap_or_default();
            writeln!(out, "- `{}` {label}{detail}", item.status)?;
        }
        out.push('\n');
    }
    Ok(out.trim_end().to_owned())
}

/// A site route `/docs/<page>[#anchor]` as a Markdown path relative to the status page.
fn relative_doc(href: &str, docs: &Path) -> Result<String> {
    let (route, anchor) = match href.split_once('#') {
        Some((route, anchor)) => (route, format!("#{anchor}")),
        None => (href, String::new()),
    };
    let page = route
        .strip_prefix("/docs/")
        .with_context(|| format!("status link `{href}` is not a /docs/ route"))?;
    let file = ["md", "mdx"]
        .iter()
        .map(|extension| format!("{page}.{extension}"))
        .find(|candidate| docs.join(candidate).is_file())
        .with_context(|| format!("status link `{href}` names no page under website/docs"))?;
    let path = match file.strip_prefix("status/") {
        Some(sibling) => sibling.to_owned(),
        None => format!("../{file}"),
    };
    Ok(format!("{path}{anchor}"))
}

/// `page` with the text between [`STATUS_BEGIN`] and [`STATUS_END`] replaced by `tables`.
fn status_page(page: &str, tables: &str) -> Result<String> {
    let (head, rest) = page
        .split_once(&format!("{STATUS_BEGIN}\n"))
        .with_context(|| format!("no line `{STATUS_BEGIN}`"))?;
    let (_, tail) = rest
        .split_once(&format!("\n{STATUS_END}\n"))
        .with_context(|| format!("no line `{STATUS_END}` after `{STATUS_BEGIN}`"))?;
    ensure!(
        !tail.contains(STATUS_BEGIN) && !head.contains(STATUS_END),
        "the status markers appear more than once"
    );
    Ok(format!(
        "{head}{STATUS_BEGIN}\n\n{tables}\n\n{STATUS_END}\n{tail}"
    ))
}

/// Runs one step and records it as a reader would see it in a terminal.
fn record(ess: &Path, directory: &Path, step: &Step) -> Result<Entry> {
    let mut command = format!("ess {}", step.args.join(" "));
    let mut process = std::process::Command::new(ess);
    process.args(step.args).current_dir(directory);
    let (output, status) = match step.tail {
        // One file for both streams, so a note on standard error stays where it was printed.
        None => {
            let log = directory.join(".site-data-output");
            let file = fs::File::create(&log).context("creating the output capture")?;
            let status = process
                .stdout(file.try_clone().context("sharing the output capture")?)
                .stderr(file)
                .status()
                .with_context(|| format!("running `{command}`"))?;
            let output = fs::read_to_string(&log).context("reading the output capture")?;
            fs::remove_file(&log).context("removing the output capture")?;
            (output, status)
        }
        Some(lines) => {
            let output = process
                .output()
                .with_context(|| format!("running `{command}`"))?;
            ensure!(
                output.stderr.is_empty(),
                "`{command}` wrote to standard error, which `| tail` would not hide: {}",
                String::from_utf8_lossy(&output.stderr)
            );
            write!(command, " | tail -n {lines}")?;
            let stdout = String::from_utf8(output.stdout).context("non-UTF-8 output")?;
            let all: Vec<&str> = stdout.lines().collect();
            let kept = all[all.len().saturating_sub(lines)..].join("\n");
            (kept, output.status)
        }
    };
    let exit_code = status
        .code()
        .with_context(|| format!("`{command}` ended without an exit status"))?;
    ensure!(exit_code == 0, "`{command}` failed:\n{output}");
    Ok(Entry {
        command,
        output: output.trim_end_matches('\n').to_owned(),
        exit_code,
    })
}

/// The `tones` of a recorded session: what each verdict word in its output means.
///
/// The renderer colours every occurrence of a key, so a bare `failed` would paint the `failed` of
/// `0 failed` as a failure. A counted verdict is therefore keyed with its count: `32 passed` is
/// true, `2 failed` or `1 error` false, and `0 failed` or `0 error` muted. `valid` and `compiled`
/// stand alone. Only words the output actually printed become keys.
fn tones<'a>(outputs: impl Iterator<Item = &'a str>) -> BTreeMap<String, &'static str> {
    let mut found = BTreeMap::new();
    for output in outputs {
        for line in output.lines() {
            let words: Vec<&str> = line
                .split(|c: char| c.is_whitespace() || c == ',' || c == ':')
                .filter(|word| !word.is_empty())
                .collect();
            for (index, word) in words.iter().enumerate() {
                match *word {
                    "valid" | "compiled" => {
                        found.insert((*word).to_owned(), "true");
                    }
                    "passed" | "failed" | "error" => {
                        let Some(count) = index
                            .checked_sub(1)
                            .and_then(|previous| words[previous].parse::<u64>().ok())
                        else {
                            continue;
                        };
                        let tone = match (*word, count) {
                            (_, 0) => "muted",
                            ("passed", _) => "true",
                            _ => "false",
                        };
                        found.insert(format!("{count} {word}"), tone);
                    }
                    _ => {}
                }
            }
        }
    }
    found
}

fn pretty(value: &impl Serialize) -> Result<String> {
    Ok(serde_json::to_string_pretty(value)? + "\n")
}

/// A directory removed when dropped.
struct Scratch(PathBuf);

impl Scratch {
    fn new() -> Result<Self> {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .context("system clock precedes the Unix epoch")?
            .as_nanos();
        let path =
            std::env::temp_dir().join(format!("ess-site-data-{}-{nonce}", std::process::id()));
        fs::create_dir_all(&path).with_context(|| format!("creating {}", path.display()))?;
        Ok(Self(path))
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn copy_tree(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to).with_context(|| format!("creating {}", to.display()))?;
    for entry in fs::read_dir(from).with_context(|| format!("reading {}", from.display()))? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_tree(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), &target)
                .with_context(|| format!("copying {}", entry.path().display()))?;
        }
    }
    Ok(())
}

