//! The data the product landing page renders: recorded `ess` sessions and the billing domain graph.
//!
//! `website/product.json` names files under `website/data/`, and the docs-system product-site
//! plugin reads them at build time. Every one of them is produced here by running the real `ess`
//! binary on a copy of [`EXAMPLE`]: the terminal sessions are `b10x-terminal/1` documents holding
//! the commands and what they printed, and the domain graphs are `b10x-domain-graph/1` documents
//! derived from `ess specify compile --format json`. The hero's `b10x-code-pair/1` quotes one
//! declared type from the example's source next to its schema in a fresh `openapi` projection.
//! Nothing in them is typed by hand, and
//! `--check` refuses a committed file that differs from a fresh recording.
//!
//! The commands run in a scratch directory holding only `examples/billing`, so the paths they
//! print are the relative paths a reader would type, and the files they write land nowhere in the
//! repository.

use anyhow::{bail, ensure, Context, Result};
use serde::Serialize;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Stdio;

/// The specification every recording runs on.
const EXAMPLE: &str = "examples/billing";

/// Where the generated files land, relative to the repository root.
const DATA: &str = "website/data";

/// Recorded in each document, since JSON carries no comment.
const RECORDED_WITH: &str =
    "ess built from this repository, recorded by `cargo xtask site-data` on a copy of examples/billing";

/// Recorded in each domain graph's `domain.source`.
const GRAPH_SOURCE: &str =
    "examples/billing, compiled by `ess specify compile`; generated by `cargo xtask site-data`";

/// The declared type the landing page's code pair quotes, in its source and in the `openapi`
/// projection, and the two files it is quoted from.
const PAIR_TYPE: &str = "billing.invoice.Money";
const PAIR_SOURCE: &str = "domains/invoice.yaml";
const PAIR_PROJECTION: &str = "openapi/invoice-service.yaml";
const PAIR_OUT: &str = "generated";
const PAIR_FILE: &str = "billing-invoice-money.code-pair.json";

/// The `b10x-status/1` record the landing page's status section reads, and the status page whose
/// capability tables are rendered from it. The page is published through the documentation
/// collection, which refuses MDX imports, so it carries the record as generated Markdown between
/// the markers instead of a `<StatusTable>` reading the file.
const STATUS_RECORD: &str = "website/data/status.json";
const STATUS_PAGE: &str = "website/docs/status/where-this-stands.md";
const STATUS_BEGIN: &str = "[ess-status-record-begin]: #";
const STATUS_END: &str = "[ess-status-record-end]: #";

/// One command of a recorded session.
struct Step {
    /// The arguments after `ess`.
    args: &'static [&'static str],
    /// Keep only the last lines of standard output, as `| tail -n N` would.
    tail: Option<usize>,
}

/// One recorded session: its file, its title and its commands, in order.
struct Session {
    file: &'static str,
    title: &'static str,
    steps: &'static [Step],
}

