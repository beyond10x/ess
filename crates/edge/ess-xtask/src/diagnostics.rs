//! `website/docs/reference/diagnostics.md`, rendered from the catalogues the owning crates export.
//!
//! Every diagnostic `ess` prints has a code a reader can look up, and until this page existed most
//! of them had nowhere to be looked up: three of thirty-seven `ESS-AUTHOR` codes and seven of
//! eighteen `ESS-SYNTH` codes were explained in the published documentation, and the compiler's
//! class numbers and the dotted history refusals not at all.
//!
//! The text is not written here. Each crate that emits a diagnostic exports a catalogue, and a test
//! in that crate fails when a code is missing from it: in `ess-conformance` the catalogue and the
//! exhaustive match that derives each refusal's code are one macro expansion, so a refusal cannot
//! be emitted without an entry; the category enums of realization, composition and deployment are
//! held to their catalogues by reading the enum's declaration; and the compiler's classes and
//! families are held to `class::ALL` and `family::ALL`. This module only lays the entries out.
//! `--check` holds the committed page to that rendering byte for byte, so a code added in a crate
//! and not on the page fails the gate, and it refuses any entry whose meaning or repair is empty.

