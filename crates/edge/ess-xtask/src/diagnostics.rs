/// Every catalogued entry whose meaning or repair is empty.
fn empty_summaries(sections: &[Section]) -> Vec<String> {
    let mut problems = Vec::new();
    for section in sections {
        for row in &section.rows {
            if row.meaning.trim().is_empty() {
                problems.push(format!("{}: {} has no meaning", section.heading, row.code));
            }
            if row.repair.trim().is_empty() {
                problems.push(format!("{}: {} has no repair", section.heading, row.code));
            }
        }
    }
    for class in codes::class::CATALOGUE {
        if class.meaning.trim().is_empty() || class.repair.trim().is_empty() {
            problems.push(format!(
                "compiler class {:03} has an empty summary",
                class.number
            ));
        }
    }
    for family in codes::family::CATALOGUE {
        if family.applies_to.trim().is_empty() {
            problems.push(format!(
                "compiler family {} has an empty summary",
                family.name
            ));
        }
    }
    problems
}

/// The class a number names, for the validation table.
fn class_name(number: u16) -> &'static str {
    codes::class::CATALOGUE
        .iter()
        .find(|class| class.number == number)
        .map_or("", |class| class.name)
}

fn render_sections(sections: &[Section]) -> String {
    let mut out = String::new();
    out.push_str(
        "---\n\
         title: Diagnostics\n\
         description: Every code and refusal name the ess specification, conformance, realization, composition and deployment commands print, what it means, and how to repair it.\n\
         ---\n\n\
         # Diagnostics\n\n",
    );
    out.push_str(BEGIN);
    out.push_str(
        "\n\n\
         Every diagnostic `ess` prints for a specification, a scenario, a suite, a history, a \
         realization, a composition or a deployment carries a stable code or name, and this page \
         lists each one with what it means and how to repair it. A harness matches on the code. \
         The sentence after it and the `help:` line are for the reader, and may be reworded \
         between releases. The `ess infra` commands report their own findings and are not listed \
         here.\n\n\
         ## Specification diagnostics: `ESS-<FAMILY>-<NNN>`\n\n\
         `ess specify validate` reports a defect in a specification twice: \
         once under its validation name in brackets, and once as a compiler diagnostic \
         with a code, a location and a repair hint:\n\n\
         ```text\n\
         \x20 - [undeclared_reference] command.billing.invoice.CreateInvoice.outcomes.accepted.emits: `billing.invoice.InvoiceRaised` is not a declared event (hint: …)\n\
         \x20 - error[ESS-COMMAND-001]: `billing.invoice.InvoiceRaised` is not a declared event\n\
         ```\n\n\
         The code has two parts. The family says which part of the specification the defect is \
         in, and the number says what kind of defect it is. A number means the same thing in \
         every family: `ESS-BINDING-002` and `ESS-VIEW-002` are both type mismatches, one in a \
         binding and one in a view. Any family can carry any class, so the two tables below \
         cover every code.\n\n\
         ### Classes\n\n\
         | Number | Class | Meaning | Repair |\n\
         |---|---|---|---|\n",
    );
    for class in codes::class::CATALOGUE {
        let _ = writeln!(
            out,
            "| `{:03}` | `{}` | {} | {} |",
            class.number,
            class.name,
            sentence(class.meaning),
            sentence(class.repair)
        );
    }
    out.push_str("\n### Families\n\n| Family | Where it applies |\n|---|---|\n");
    for family in codes::family::CATALOGUE {
        let _ = writeln!(
            out,
            "| `{}` | {} |",
            family.name,
            sentence(family.applies_to)
        );
    }
    out.push_str(
        "\n### Validation names\n\n\
         Each bracketed validation name is reported under the class below. Its family is the \
         construct the defect is in.\n\n\
         | Validation name | Class |\n\
         |---|---|\n",
    );
    for code in ValidationCode::ALL {
        let number = class_of(*code);
        let _ = writeln!(
            out,
            "| `{}` | `{number:03}` `{}` |",
            code.as_str(),
            class_name(number)
        );
    }
    out.push('\n');
    for section in sections {
        let _ = write!(out, "## {}\n\n{}\n\n", section.heading, section.intro);
        table(&mut out, section.code_header, &section.rows);
    }
    out.push_str(END);
    out.push('\n');
    out
}

/// The whole page, or every entry with an empty summary.
pub fn render() -> Result<String> {
    let sections = sections();
    let problems = empty_summaries(&sections);
    if !problems.is_empty() {
        bail!(
            "a catalogued diagnostic has no summary; write it in the crate's catalogue:\n  {}",
            problems.join("\n  ")
        );
    }
    Ok(render_sections(&sections))
}

/// Writes the page, or with `check` compares the committed one with it.
pub fn run(root: &Path, check: bool) -> Result<String> {
    let rendered = render()?;
    let path = root.join(PAGE);
    if !check {
        fs::write(&path, &rendered)?;
        return Ok(format!("{PAGE}: written\n"));
    }
    let committed = fs::read_to_string(&path).unwrap_or_default();
    if committed != rendered {
        bail!(
            "{PAGE} is not what the diagnostic catalogues render to; run `cargo xtask \
             diagnostics`. A diagnostic was added, removed or reworded in a crate and the page \
             was left behind."
        );
    }
    Ok(format!(
        "{PAGE}: byte-identical to the diagnostic catalogues\n"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_cell_escapes_what_mdx_and_a_table_would_read() {
        assert_eq!(
            cell("declare `Optional<T>` or {x} | y <z>"),
            "declare `Optional<T>` or &#123;x&#125; \\| y &lt;z&gt;"
        );
        assert_eq!(cell("`a|b`"), "`a\\|b`");
        assert_eq!(sentence(" name a view"), "Name a view.");
        assert_eq!(
            sentence("`drop` is unobservable."),
            "`drop` is unobservable."
        );
    }

    #[test]
    fn the_page_has_a_row_for_every_code_the_story_names() {
        let page = render().expect("every catalogued diagnostic has a summary");
        for number in 1..=37 {
            assert!(
                page.contains(&format!("| `ESS-AUTHOR-{number:03}` |")),
                "AUTHOR {number}"
            );
        }
        for number in 1..=18 {
            assert!(
                page.contains(&format!("| `ESS-SYNTH-{number:03}` |")),
                "SYNTH {number}"
            );
            assert!(
                page.contains(&format!("| `{number:03}` |")),
                "class {number}"
            );
        }
        for number in 1..=5 {
            assert!(
                page.contains(&format!("| `ESS-MUTATE-{number:03}` |")),
                "MUTATE {number}"
            );
        }
        for family in codes::family::ALL {
            assert!(page.contains(&format!("| `{family}` |")), "family {family}");
        }
        assert_eq!(
            page.matches("| `history.").count(),
            15,
            "the dotted refusals"
        );
        for code in ValidationCode::ALL {
            assert!(
                page.contains(&format!("| `{}` |", code.as_str())),
                "{code:?}"
            );
        }
    }

    #[test]
    fn an_empty_summary_is_refused_by_name() {
        let sections = vec![Section {
            heading: "Test",
            intro: "",
            code_header: "Code",
            rows: vec![Row {
                code: "`X-1`".to_owned(),
                meaning: " ",
                repair: "fix it",
            }],
        }];
        assert_eq!(empty_summaries(&sections), ["Test: `X-1` has no meaning"]);
    }
}
