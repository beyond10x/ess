/// The rendered page, relative to the repository root.
pub const PAGE: &str = "website/docs/reference/diagnostics.md";

const BEGIN: &str = "[ess-diagnostics-begin]: # (generated by cargo xtask diagnostics from the \
                     catalogue each crate exports; change the catalogue, then run the command)";
const END: &str = "[ess-diagnostics-end]: #";

/// One row of a code table.
struct Row {
    code: String,
    meaning: &'static str,
    repair: &'static str,
}

/// Rows for a numbered family, `ESS-<family>-<nnn>`, in code order.
fn numbered(family: &'static str, entries: &[CatalogueEntry<u16>]) -> Vec<Row> {
    let mut entries: Vec<&CatalogueEntry<u16>> = entries.iter().collect();
    entries.sort_by_key(|entry| entry.key);
    entries
        .into_iter()
        .map(|entry| Row {
            code: format!("`{}`", Code::new(family, entry.key)),
            meaning: entry.meaning,
            repair: entry.repair,
        })
        .collect()
}

/// Rows for a family whose key is printed as `name` renders it, in catalogue order.
fn named<K>(entries: &[CatalogueEntry<K>], name: impl Fn(&K) -> String) -> Vec<Row> {
    entries
        .iter()
        .map(|entry| Row {
            code: name(&entry.key),
            meaning: entry.meaning,
            repair: entry.repair,
        })
        .collect()
}

/// A category's name as a JSON report spells it.
fn wire<K: serde::Serialize>(key: &K) -> String {
    match serde_json::to_value(key) {
        Ok(serde_json::Value::String(name)) => name,
        other => panic!("a diagnostic category serializes as a string, not {other:?}"),
    }
}

/// One sentence as a table cell: trimmed, its first letter upper case, ending in a full stop.
fn sentence(text: &str) -> String {
    let text = text.trim();
    let mut characters = text.chars();
    let mut out = match characters.next() {
        Some(first) => first.to_uppercase().chain(characters).collect(),
        None => String::new(),
    };
    if !out.ends_with('.') {
        out.push('.');
    }
    cell(&out)
}

/// Escapes text for a Markdown table cell that MDX also reads.
///
/// Outside a code span, `<`, `>`, `{` and `}` start JSX in MDX, so they become entities there. A
/// `|` ends a table cell anywhere, code span included, so it is escaped everywhere.
fn cell(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for (index, segment) in text.split('`').enumerate() {
        if index > 0 {
            out.push('`');
        }
        let in_code = index % 2 == 1;
        for character in segment.chars() {
            match character {
                '|' => out.push_str("\\|"),
                '\n' => out.push(' '),
                '<' if !in_code => out.push_str("&lt;"),
                '>' if !in_code => out.push_str("&gt;"),
                '{' if !in_code => out.push_str("&#123;"),
                '}' if !in_code => out.push_str("&#125;"),
                other => out.push(other),
            }
        }
    }
    out
}

fn table(out: &mut String, code_header: &str, rows: &[Row]) {
    let _ = writeln!(out, "| {code_header} | Meaning | Repair |");
    out.push_str("|---|---|---|\n");
    for row in rows {
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            row.code,
            sentence(row.meaning),
            sentence(row.repair)
        );
    }
    out.push('\n');
}

