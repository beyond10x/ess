fn disk_fixture(directory: &Path) -> EssIr {
    let mut paths = Vec::new();
    let mut pending = vec![directory.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                pending.push(path);
            } else if path.extension().is_some_and(|ext| ext == "yaml") {
                paths.push(path);
            }
        }
    }
    paths.sort();
    let documents = paths
        .iter()
        .map(|path| {
            (
                path.strip_prefix(directory).unwrap().display().to_string(),
                std::fs::read_to_string(path).unwrap(),
            )
        })
        .collect::<Vec<_>>();
    fixture(
        &documents
            .iter()
            .map(|(path, text)| (path.as_str(), text.as_str()))
            .collect::<Vec<_>>(),
    )
}

#[test]
fn complete_committed_valid_artifact_maps_are_unchanged_and_compile() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    for example in ["billing", "gatepass"] {
        let ir = disk_fixture(&root.join("examples").join(example));
        let directory = scratch(example);
        for target in if example == "billing" {
            &[Target::Rust, Target::Web][..]
        } else {
            &[Target::Rust][..]
        } {
            let target = *target;
            let synthesis = synthesize_for(&ir, target).expect("committed valid realization");
            let relative = format!("generated/{}/{example}", target.name());
            let committed = root.join(&relative);
            let mut pending = vec![committed.clone()];
            let mut observed = std::collections::BTreeSet::new();
            while let Some(dir) = pending.pop() {
                for entry in std::fs::read_dir(dir).unwrap() {
                    let path = entry.unwrap().path();
                    if path.is_dir() {
                        pending.push(path);
                    } else {
                        let relative = path.strip_prefix(&committed).unwrap().display().to_string();
                        assert_eq!(
                            std::fs::read(&path).unwrap(),
                            synthesis.artifacts[&relative].contents.as_bytes(),
                            "historical bytes: {}",
                            path.display()
                        );
                        observed.insert(relative);
                    }
                }
            }
            assert_eq!(observed, synthesis.artifacts.keys().cloned().collect());
            assert_eq!(
                synthesis.plan.to_canonical_json(),
                SynthesisPlan::of(&ir).to_canonical_json()
            );
            write_emission(&directory.join(&relative), &synthesis);
            check_generated_for(
                &directory.join(&relative),
                (target == Target::Web).then_some("wasm32-unknown-unknown"),
            );
        }
    }
}

