fn replay_probe(directory: &Path) {
    let harness = directory.join("replay-harness");
    std::fs::create_dir_all(harness.join("src")).unwrap();
    std::fs::write(
        harness.join("Cargo.toml"),
        r#"[workspace]
resolver = "2"
[package]
name = "replay-proof"
version = "0.0.0"
edition = "2021"
[lib]
crate-type = ["cdylib"]
[dependencies]
demo-web = { path = "../generated/web/demo/crates/demo-web" }
demo-types = { path = "../generated/rust/demo/crates/demo-types" }
demo-system = { path = "../generated/rust/demo/crates/demo-system" }
worker = { path = "../generated/rust/demo/crates/worker" }
"#,
    )
    .unwrap();
    std::fs::write(
        harness.join("src/lib.rs"),
        r#"use demo_web::{Bound, BridgeError};
use demo_types::core::{Fire, FireOutcome, Fired};
struct Behavior;
impl demo_types::core::obligations::FireBehavior for Behavior {
    fn fire(&mut self, _: Fire) -> Result<FireOutcome, demo_types::obligation::UnmetObligation> {
        Ok(FireOutcome::Done { fired: Fired { value: "retained".to_owned() } })
    }
}
#[no_mangle]
pub extern "C" fn replay_proof() -> u32 {
    let mut system = demo_system::System::new(worker::Worker::new(Behavior));
    system.worker.fire(Fire {}).unwrap();
    system.pump().unwrap();
    assert_eq!(system.published().len(), 1);
    let before = system.published().to_vec();
    assert_eq!(Bound::replay(&mut system, 0), Ok(()));
    assert_eq!(system.published(), before);
    assert_eq!(Bound::replay(&mut system, 1), Err(BridgeError::NoSuchOccurrence(1)));
    assert_eq!(system.published(), before);
    73
}
"#,
    )
    .unwrap();
    let before_rust = generated_bytes(&directory.join("generated/rust/demo"));
    let before_web = generated_bytes(&directory.join("generated/web/demo"));
    let lock = cargo(&harness, "lock", &["generate-lockfile", "--offline"]);
    assert!(lock.status.success());
    let build = cargo(
        &harness,
        "wasm-build",
        &[
            "build",
            "--locked",
            "--offline",
            "--target",
            "wasm32-unknown-unknown",
            "--target-dir",
            "target",
        ],
    );
    assert!(
        build.status.success(),
        "the independent WASM replay harness compiles"
    );
    let mut command = Command::new("node");
    command.current_dir(&harness).args(["-e", "const fs=require('node:fs'); WebAssembly.instantiate(fs.readFileSync('target/wasm32-unknown-unknown/debug/replay_proof.wasm'),{}).then(({instance})=>{const answer=instance.exports.replay_proof(); if(answer!==73) throw Error(String(answer)); console.log('replay existing occurrence: no delivery; missing occurrence: NoSuchOccurrence; log unchanged');}).catch(e=>{console.error(e);process.exit(1);});"]);
    std::fs::write(harness.join("node.command"), format!("{command:?}\n")).unwrap();
    let output = command
        .output()
        .expect("Node is a required local WASM validation prerequisite");
    std::fs::write(harness.join("node.stdout"), &output.stdout).unwrap();
    std::fs::write(harness.join("node.stderr"), &output.stderr).unwrap();
    std::fs::write(harness.join("node.exit"), output.status.to_string()).unwrap();
    eprintln!(
        "{command:?}\n{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        output.status.success(),
        "the real generated Bound::replay must execute under WASM"
    );
    assert_eq!(
        before_rust,
        generated_bytes(&directory.join("generated/rust/demo"))
    );
    assert_eq!(
        before_web,
        generated_bytes(&directory.join("generated/web/demo"))
    );
}

