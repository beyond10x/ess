/// The fixture directory.
fn fixture_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/declared-behaviour")
}

/// A specification directory, compiled where it lives.
fn compile_directory(base: &Path) -> EssIr {
    let mut labels = Vec::new();
    let mut pending = vec![base.to_path_buf()];
    while let Some(directory) = pending.pop() {
        for entry in std::fs::read_dir(&directory).expect("the fixture is readable") {
            let path = entry.expect("an entry").path();
            if path.is_dir() {
                pending.push(path);
            } else if path.extension().is_some_and(|it| it == "yaml") {
                labels.push(
                    path.strip_prefix(base)
                        .expect("inside the fixture")
                        .display()
                        .to_string(),
                );
            }
        }
    }
    labels.sort();
    let mut sources = SourceMap::new();
    let mut parsed = Vec::new();
    for label in &labels {
        let text = std::fs::read_to_string(base.join(label)).expect("readable");
        let raw = RawSpecFile::parse(&text)
            .unwrap_or_else(|error| panic!("{label} is well formed: {error}"));
        sources.insert(label.clone(), text);
        parsed.push((Source::new(label.clone()), raw));
    }
    let specification = Specification::assemble(parsed)
        .unwrap_or_else(|errors| panic!("the fixture validates:\n{errors}"));
    compile_locating(&specification, &sources, &labels)
        .unwrap_or_else(|diagnostics| panic!("the fixture resolves:\n{diagnostics}"))
}

/// One YAML document, compiled.
fn compile_text(text: &str) -> EssIr {
    let raw = RawSpecFile::parse(text).unwrap_or_else(|error| panic!("well formed: {error}"));
    let specification = Specification::assemble([(Source::new("model.yaml"), raw)])
        .unwrap_or_else(|errors| panic!("validates:\n{errors}"));
    let mut sources = SourceMap::new();
    sources.insert("model.yaml".to_owned(), text.to_owned());
    compile_locating(&specification, &sources, &["model.yaml".to_owned()])
        .unwrap_or_else(|diagnostics| panic!("resolves:\n{diagnostics}"))
}

#[test]
fn the_plan_generates_every_fully_declared_command_and_keeps_the_view_owed() {
    let ir = compile_directory(&fixture_root());
    let synthesis = synthesize_for(&ir, Target::Rust).expect("the fixture synthesizes");
    for command in ir.commands().keys() {
        assert_eq!(
            synthesis
                .plan
                .disposition_of(CapabilityKind::CommandBehavior, &command.to_string()),
            Some(&SynthesisDisposition::Generated),
            "`{command}` is fully declared, so its behaviour is generated"
        );
    }
    assert!(matches!(
        synthesis
            .plan
            .disposition_of(CapabilityKind::ViewQuery, "desk.ticket.Tickets"),
        Some(SynthesisDisposition::Obligation(_))
    ));
    let behaviour = synthesis
        .artifacts
        .get("crates/desk-types/src/behaviour.rs")
        .expect("the types crate carries the generated behaviours");
    for port in [
        "pub trait TicketStorage",
        "pub trait Context",
        "pub struct Generated<P>",
        "fn external(&mut self, command: &'static str, outcome: &'static str) -> bool;",
        "fn caller_agent_id(&self) -> Option<crate::ticket::AgentId>;",
        "fn generate_desk_ticket_ticket_id(&mut self) -> crate::ticket::TicketId;",
    ] {
        assert!(
            behaviour.contents.contains(port),
            "`{port}` missing:\n{}",
            behaviour.contents
        );
    }
    assert!(
        !behaviour.contents.contains("impl Unimplemented")
            && !synthesis
                .artifacts
                .values()
                .any(|artifact| artifact.contents.contains("impl TicketStorage for")),
        "ess generates the storage trait, never a store"
    );
    let domain = &synthesis.artifacts["crates/desk-types/src/ticket.rs"].contents;
    assert!(
        !domain.contains("impl OpenTicketBehavior for Unimplemented"),
        "a generated behaviour is not stubbed as owed"
    );
    assert!(domain.contains("pub trait OpenTicketBehavior"), "{domain}");
}

#[test]
fn a_moved_or_written_entity_is_checked_against_its_invariants_before_it_is_stored() {
    let ir = compile_directory(&fixture_root());
    let with_invariant = fixture_with_invariant();
    let plain = synthesize_for(&ir, Target::Rust).expect("synthesizes");
    let checked = synthesize_for(&with_invariant, Target::Rust).expect("synthesizes");
    let behaviour = |synthesis: &ess_synth::Synthesis| {
        synthesis.artifacts["crates/desk-types/src/behaviour.rs"]
            .contents
            .clone()
    };
    assert!(
        !behaviour(&plain).contains("broken_invariant"),
        "an entity declaring no invariant has no check to call"
    );
    let text = behaviour(&checked);
    // Every write of the entity — the create, both moves, the three updates — is preceded by the
    // check.
    let puts = text.matches("TicketStorage::put(").count();
    let checks = text.matches(".broken_invariant()").count();
    assert_eq!(puts, 6, "{text}");
    assert_eq!(checks, puts, "{text}");
    for (position, _) in text.match_indices("TicketStorage::put(") {
        let before = &text[..position];
        let check = before
            .rfind(".broken_invariant()")
            .expect("a check before the write");
        let previous_put = before.rfind("TicketStorage::put(").unwrap_or(0);
        assert!(
            check > previous_put,
            "the check precedes its own write:\n{text}"
        );
    }
}

/// The fixture with `estimate >= 0` declared on the ticket.
fn fixture_with_invariant() -> EssIr {
    let base = fixture_root();
    let mut labels = vec![
        "components.yaml".to_owned(),
        "domains/ticket.yaml".to_owned(),
        "system.yaml".to_owned(),
    ];
    labels.sort();
    let mut sources = SourceMap::new();
    let mut parsed = Vec::new();
    for label in &labels {
        let mut text = std::fs::read_to_string(base.join(label)).expect("readable");
        if label == "domains/ticket.yaml" {
            text = text.replace(
                "      - {name: note, type: Optional<String>}\n    lifecycle:",
                "      - {name: note, type: Optional<String>}\n    invariants:\n      - estimate >= 0\n    lifecycle:",
            );
        }
        let raw = RawSpecFile::parse(&text).expect("well formed");
        sources.insert(label.clone(), text);
        parsed.push((Source::new(label.clone()), raw));
    }
    let specification = Specification::assemble(parsed).expect("validates");
    compile_locating(&specification, &sources, &labels).expect("resolves")
}

