#[test]
fn every_construct_the_story_keeps_owed_keeps_its_whole_command_an_obligation() {
    let cases = [
        Kept {
            model: RELATED_GUARD,
            command: "kept.shop.PlaceOrder",
            names: "`when_related:`",
        },
        Kept {
            model: RELATED_SET,
            command: "kept.shop.PlaceOrder",
            names: "`{related:}`",
        },
        Kept {
            model: STATE_AND_EXTERNAL,
            command: "kept.shop.Ship",
            names: "`when_subject_state:` beside `external:`",
        },
        Kept {
            model: MOVE_OR_UPDATE,
            command: "kept.shop.Ship",
            names: "a subject predicate choosing between a move and an update",
        },
        Kept {
            model: NO_UNKNOWN_ANSWER,
            command: "kept.shop.Ship",
            names: "an unknown identity",
        },
        Kept {
            model: SET_OUTCOME,
            command: "kept.shop.ShipAll",
            names: "`instances:`",
        },
        Kept {
            model: AFFECTS,
            command: "kept.shop.Ship",
            names: "`affects:`",
        },
        Kept {
            model: UNDETERMINED_ERROR,
            command: "kept.shop.PlaceOrder",
            names: "the fields of error `kept.shop.TooMany`",
        },
        Kept {
            model: UNDETERMINED_FIELD,
            command: "kept.shop.PlaceOrder",
            names: "`creates:` leaving the required field `quantity`",
        },
    ];
    for case in cases {
        let ir = compile_text(case.model);
        // The plan, not a target: `instances:` and `affects:` are refused by the Rust target as a
        // whole, and the plan still names the construct that keeps the command owed.
        let plan = SynthesisPlan::of(&ir);
        match plan.disposition_of(CapabilityKind::CommandBehavior, case.command) {
            Some(SynthesisDisposition::Obligation(obligation)) => {
                let why = obligation.reason.describes();
                assert!(
                    why.contains(case.names),
                    "`{}` names `{}` as what kept it owed, not: {why}",
                    case.command,
                    case.names
                );
            }
            other => panic!("`{}` stays an obligation, not {other:?}", case.command),
        }
        let markdown = plan.to_markdown();
        assert!(markdown.contains(case.names), "{markdown}");
        // The sibling in each model is fully declared and generated: the line is per command.
        assert_eq!(
            plan.disposition_of(CapabilityKind::CommandBehavior, "kept.shop.OpenShop"),
            Some(&SynthesisDisposition::Generated),
            "{}",
            case.command
        );
    }
}

