//! A fully declared command's behaviour is generated over storage and context ports
//! (`story:generated-behaviour-for-declared-commands`).
//!
//! The fixture under `tests/fixtures/declared-behaviour/` declares every construct the story names
//! as expressible: `when:`, `when_subject:`, `when_subject_state:`, `unknown_instance:`,
//! `wrong_state:`, a default, `external:` with and without an input guard; `creates:`, `moves:`,
//! `updates:`, `deletes:`; `sets:` from input, a literal, `{increment:}`, `{cleared}`, the caller and
//! `{generated: true}`; payloads from input, subject fields, the caller and generated values. Its
//! Rust workspace is synthesized, the in-memory port implementation in
//! `tests/fixtures/declared-behaviour-harness/` is placed beside it (outside the generated bytes,
//! holding no command behaviour), and the suite the same specification synthesizes runs against
//! the generated behaviours through that harness.

