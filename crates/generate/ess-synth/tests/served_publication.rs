/// Every served command answer the harness printed validates against the response schema the
/// same server serves at `/openapi.json` for that path and status — `published` included, under
/// `additionalProperties: false`.
#[test]
fn every_served_answer_validates_against_the_contract_the_server_serves() {
    let lines = run("contract", OutputLayout::Workspace);
    let contract: serde_json::Value = serde_json::from_str(
        lines
            .iter()
            .find_map(|line| line.strip_prefix("contract "))
            .expect("the harness printed the served contract"),
    )
    .expect("the served contract is JSON");
    let ir = ir();
    let paths: Vec<(String, String)> = route_table(&ir)
        .chunks(3)
        .map(|row| (row[0].clone(), row[2].clone()))
        .collect();
    let path_of = |command: &str| {
        paths
            .iter()
            .find(|(name, _)| name == command)
            .map(|(_, path)| path.clone())
            .expect("a route")
    };
    let mut validated = 0;
    for line in &lines {
        let (command, rest) = if let Some(rest) = line.strip_prefix("note served ") {
            ("ops.core.Note", rest)
        } else if let Some((_, rest)) = line.split_once(" served ") {
            ("ops.core.Open", rest)
        } else {
            continue;
        };
        let (status, rest) = rest.split_once(' ').expect("a status");
        let body = rest.rsplit_once(" kept=").expect("a kept count").0;
        let answer: serde_json::Value = serde_json::from_str(body).expect("the answer is JSON");
        let schema_at = &contract["paths"][path_of(command)]["post"]["responses"][status]
            ["content"]["application/json"]["schema"];
        assert!(
            schema_at.is_object(),
            "the contract declares `{command}` answering {status}"
        );
        let mut schema = contract.clone();
        schema["$ref"] = schema_at["$ref"].clone();
        if schema_at.get("$ref").is_none() {
            schema["oneOf"] = schema_at["oneOf"].clone();
        }
        let validator = jsonschema::draft202012::new(&schema)
            .unwrap_or_else(|error| panic!("the served contract compiles as a schema: {error}"));
        let errors: Vec<String> = validator
            .iter_errors(&answer)
            .map(|error| format!("{error} at {}", error.instance_path()))
            .collect();
        assert!(
            errors.is_empty(),
            "`{command}` {status} {answer} does not validate against the served contract: \
             {errors:?}"
        );
        validated += 1;
    }
    assert_eq!(validated, 4, "every served command answer was validated");

    // The other direction: an answer that lists an event the branch does not publish, or drops
    // `published`, is refused by the same schema — the contract states the list, not just a key.
    let opened = &contract["components"]["schemas"]["ops.core.Open.opened.Response"];
    assert_eq!(
        opened["required"],
        serde_json::json!(["outcome", "published"])
    );
    let mut schema = contract.clone();
    schema["$ref"] = serde_json::json!("#/components/schemas/ops.core.Open.opened.Response");
    let validator = jsonschema::draft202012::new(&schema).expect("compiles");
    for wrong in [
        serde_json::json!({"outcome": "opened"}),
        serde_json::json!({"outcome": "opened", "published": []}),
        serde_json::json!({"outcome": "opened", "published": [
            {"event": "ops.core.Noted", "payload": {"id": "t"}}
        ]}),
    ] {
        assert!(!validator.is_valid(&wrong), "the contract refuses {wrong}");
    }
}

