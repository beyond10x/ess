/// The answer lines of [`events`], as [`HARNESS`] prints them.
fn events_answers(layout: OutputLayout) -> Vec<&'static str> {
    events(layout)
        .iter()
        .filter(|line| line.starts_with("open ") || line.starts_with("note "))
        .map(String::as_str)
        .collect()
}
