/// `body` with every helper whose name is an imported package's moved out of its way, as a local
/// is (`fresh`): a domain package called `equal` and a helper called `equal` are one name declared
/// twice in this file.
///
/// Identifiers only — never one inside a comment, a string or a rune, and never one beside a `.`,
/// which is a package qualifier (`equal.TaskId`) or a selector, not a helper. A model whose
/// package names meet no helper keeps every byte.
fn rename_helpers(body: &str, reserved: &BTreeSet<String>) -> String {
    let mut taken: BTreeSet<String> = reserved.clone();
    taken.extend(HELPER_NAMES.iter().map(|name| (*name).to_owned()));
    let renamed: BTreeMap<&str, String> = HELPER_NAMES
        .iter()
        .filter(|name| reserved.contains(**name))
        .map(|name| (*name, fresh(&taken, name)))
        .collect();
    if renamed.is_empty() {
        return body.to_owned();
    }
    let bytes = body.as_bytes();
    let mut out = String::with_capacity(body.len());
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        let rest = &body[index..];
        if rest.starts_with("//") {
            let end = rest.find('\n').map_or(body.len(), |at| index + at);
            out.push_str(&body[index..end]);
            index = end;
        } else if byte == b'"' || byte == b'\'' || byte == b'`' {
            let mut end = index + 1;
            while end < bytes.len() && bytes[end] != byte {
                if bytes[end] == b'\\' && byte != b'`' {
                    end += 1;
                }
                end += 1;
            }
            let end = (end + 1).min(bytes.len());
            out.push_str(&body[index..end]);
            index = end;
        } else if byte.is_ascii_alphabetic() || byte == b'_' {
            let mut end = index + 1;
            while end < bytes.len() && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_') {
                end += 1;
            }
            let word = &body[index..end];
            // A word after one `.` is a selector or follows a package qualifier; after the variadic
            // `...` it is a type, and a helper.
            let selected = index > 0
                && bytes[index - 1] == b'.'
                && !(index >= 3 && &body[index - 3..index] == "...");
            let qualified = selected || bytes.get(end) == Some(&b'.');
            match renamed.get(word) {
                Some(replacement) if !qualified => out.push_str(replacement),
                _ => out.push_str(word),
            }
            index = end;
        } else {
            let width = rest.chars().next().map_or(1, char::len_utf8);
            out.push_str(&body[index..index + width]);
            index += width;
        }
    }
    out
}

/// The storage interface name of each entity: `<Type>Storage`, or — where two entities of
/// different domains share a type name — every one spelled from its full name.
fn storage_names(ir: &EssIr, layout: &Layout) -> BTreeMap<QualifiedName, String> {
    let short: BTreeMap<QualifiedName, String> = ir
        .entities()
        .keys()
        .map(|entity| {
            (
                entity.clone(),
                format!("{}Storage", layout.declared(entity)),
            )
        })
        .collect();
    let distinct: BTreeSet<&String> = short.values().collect();
    if distinct.len() == short.len() {
        return short;
    }
    ir.entities()
        .keys()
        .map(|entity| {
            (
                entity.clone(),
                format!("{}Storage", name::type_fragment(&entity.to_string())),
            )
        })
        .collect()
}

/// One entity's storage port.
fn storage_interface(
    out: &mut String,
    emit: &Emit<'_>,
    storages: &BTreeMap<QualifiedName, String>,
    entity: &QualifiedName,
    listed: bool,
) {
    let declared = emit.ir.entities()[entity].clone();
    let snapshot = emit.qualify(emit.layout.package_of(entity), emit.layout.snapshot(entity));
    let identity = emit.go_type(&declared.identity.type_ref);
    let list = if listed {
        format!(
            "\n\n\t// List is every stored instance, in an order the store keeps stable: the \
             order a\n\t// generated query answers an unordered view in.\n\tList() []{snapshot}"
        )
    } else {
        String::new()
    };
    let _ = writeln!(
        out,
        "\n// {} is where `{entity}` is stored — a port the implementor provides.\n//\n// Keyed by \
         the identity `{}`. ess generates this interface and never an implementation of \
         it.\ntype {} interface {{\n\t// Get is the instance with this identity and true, or \
         false where none is stored.\n\tGet(identity {identity}) ({snapshot}, bool)\n\n\t// Put \
         stores this instance under its identity, replacing what was held.\n\tPut(snapshot \
         {snapshot})\n\n\t// Delete removes the instance with this identity.\n\tDelete(identity \
         {identity}){list}\n}}",
        storages[entity], declared.identity.name, storages[entity]
    );
}

/// The context port: only the methods some generated method asks. `true` where there is one.
fn context_interface(out: &mut String, uses: &Uses) -> bool {
    if uses.callers.is_empty() && uses.generates.is_empty() && !uses.external {
        return false;
    }
    out.push_str(
        "\n// Context is what the specification leaves to the implementor's context — a port the\n// \
         implementor provides.\n//\n// The caller's attributes, the values the model says the \
         implementation assigns, and the answer\n// to each `external:` branch.\ntype Context \
         interface {\n",
    );
    let mut first = true;
    let mut separate = |out: &mut String| {
        if !first {
            out.push('\n');
        }
        first = false;
    };
    for (method, (ty, attribute)) in &uses.callers {
        separate(out);
        let _ = writeln!(
            out,
            "\t// {method} is the authenticated caller's `{attribute}` and true, or false where \
             the caller\n\t// carries none.\n\t{method}() ({ty}, bool)"
        );
    }
    for (method, (ty, of)) in &uses.generates {
        separate(out);
        let _ = writeln!(
            out,
            "\t// {method} is a new `{of}`, which the model says the implementation assigns — a\n\t// \
             created identity, a `{{generated: true}}` value, or an event field the model \
             leaves\n\t// undetermined.\n\t{method}() {ty}"
        );
    }
    if uses.external {
        separate(out);
        out.push_str(
            "\t// External reports whether the external branch outcome of command is taken on \
             this\n\t// invocation.\n\t//\n\t// Asked in declaration order, before the branch's \
             input guard is read; the first branch\n\t// answered true whose guard holds is \
             taken. A test forces a branch by answering true for\n\t// it alone; a deployment \
             asks whatever decides it.\n\tExternal(command string, outcome string) bool\n",
        );
    }
    out.push_str("}\n");
    true
}

/// The interface bundling every seam `Generated` forwards. `true` where there is one.
fn owed_interface(out: &mut String, emit: &Emit<'_>, ir: &EssIr, seams: &Seams) -> bool {
    let mut embedded = Vec::new();
    for command in ir.commands().values() {
        if seams.forwards(CapabilityKind::CommandBehavior, &command.name.to_string()) {
            embedded.push(emit.qualify(
                emit.layout.package_of(&command.name),
                emit.layout.behavior(&command.name),
            ));
        }
    }
    for view in ir.views().values() {
        if seams.forwards(CapabilityKind::ViewQuery, &view.name.to_string()) {
            embedded.push(emit.qualify(
                emit.layout.package_of(&view.name),
                emit.layout.query(&view.name),
            ));
        }
    }
    if embedded.is_empty() {
        return false;
    }
    let _ = writeln!(
        out,
        "\n// Owed is every behaviour and query the plan still owes, which [Generated] forwards \
         to — a\n// port the implementor provides.\ntype Owed interface {{\n{}}}",
        embedded.iter().fold(String::new(), |mut lines, seam| {
            let _ = writeln!(lines, "\t{seam}");
            lines
        })
    );
    true
}

/// `Ports`: one field per port.
fn ports_struct(
    out: &mut String,
    storages: &BTreeMap<QualifiedName, String>,
    uses: &Uses,
    context: bool,
    owed: bool,
) {
    out.push_str(
        "\n// Ports is everything the generated behaviours and queries read, and everything the \
         plan still\n// owes.\ntype Ports struct {\n",
    );
    for entity in &uses.storages {
        let storage = &storages[entity];
        let _ = writeln!(
            out,
            "\t// {storage} is where `{entity}` is stored.\n\t{storage} {storage}"
        );
    }
    if context {
        out.push_str(
            "\t// Context is the caller, the assigned values and the external answers.\n\tContext \
             Context\n",
        );
    }
    if owed {
        out.push_str(
            "\t// Owed answers every behaviour and query the plan still owes.\n\tOwed Owed\n",
        );
    }
    out.push_str("}\n");
}

/// Forwards one owed behaviour to `Ports.Owed`.
fn forward_behaviour(out: &mut String, emit: &Emit<'_>, receiver: &str, command: &ResolvedCommand) {
    let method = emit.layout.declared(&command.name);
    let input = emit.reference(&command.name);
    let outcome = emit.reference_outcome(&command.name);
    let unmet = emit.unmet();
    let _ = writeln!(
        out,
        "\n// {method} forwards the owed behaviour `{}` to the ports.\nfunc ({receiver} \
         *Generated) {method}(input {input}) ({outcome}, {unmet}) {{\n\treturn \
         {receiver}.ports.Owed.{method}(input)\n}}",
        command.name
    );
}

/// Forwards one owed query to `Ports.Owed`, with the parameters the view declares.
fn forward_query(
    out: &mut String,
    emit: &Emit<'_>,
    receiver: &str,
    view: &ess_compiler::ir::ResolvedView,
) {
    let params = super::port::view_params(emit, view, &[receiver]);
    let signature = super::port::signature(&params);
    let arguments = super::port::arguments(&params);
    let view = &view.name;
    let method = emit.layout.declared(view);
    let row = emit.reference(view);
    let unmet = emit.unmet();
    let _ = writeln!(
        out,
        "\n// {method} forwards the owed query `{view}` to the ports.\nfunc ({receiver} *Generated) \
         {method}({signature}) ([]{row}, {unmet}) {{\n\treturn {receiver}.ports.Owed.{method}({arguments})\n}}"
    );
}

/// The private helpers the methods call, only those some method uses, in a fixed order.
fn helpers(out: &mut String, emit: &Emit<'_>, uses: &Uses) {
    let mut wanted = uses.helpers.clone();
    // What each helper calls, so a used helper brings its own.
    let needs: &[(&str, &[&str])] = &[
        ("compareNumbers", &["numberParts", "truth", "known"]),
        ("numberKey", &["numberParts"]),
        ("numberOrder", &["numberParts"]),
        ("sumValues", &["numberParts", "fitsWide"]),
        ("average", &["spell", "fitsWide"]),
        ("instantKey", &["instant"]),
        ("instantOrder", &["instant"]),
        ("equal", &["truth", "known"]),
        ("known", &["truth"]),
        ("not", &["truth"]),
        ("allOf", &["truth"]),
        ("anyOf", &["truth"]),
        ("truthOf", &["truth", "known"]),
        ("textMatch", &["truth", "known"]),
        ("undeclared", &[]),
    ];
    let mut changed = true;
    while changed {
        changed = false;
        for (helper, requires) in needs {
            if wanted.contains(helper) {
                for required in *requires {
                    changed |= wanted.insert(required);
                }
            }
        }
    }
    for (helper, imports, text) in HELPERS {
        if wanted.contains(helper) {
            for import in *imports {
                emit.import(import);
            }
            let text = if *helper == "undeclared" || *helper == "unrepresentable" {
                text.replace("UNMET", &emit.unmet()).replace(
                    "OBLIGATION",
                    &emit.qualify(emit.layout.obligation(), "UnmetObligation"),
                )
            } else {
                (*text).to_owned()
            };
            out.push_str(&text);
        }
    }
}

