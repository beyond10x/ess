/// Everything rendering one command's method needs.
struct Writer<'a> {
    ir: &'a EssIr,
    emit: &'a Emit<'a>,
    command: &'a ResolvedCommand,
    storages: &'a BTreeMap<QualifiedName, String>,
    uses: &'a mut Uses,
    lines: Lines,
    reserved: &'a BTreeSet<String>,
    receiver: &'a str,
    locals: Locals,
    next: usize,
}

impl<'a> Writer<'a> {
    fn new(
        emit: &'a Emit<'a>,
        command: &'a ResolvedCommand,
        storages: &'a BTreeMap<QualifiedName, String>,
        uses: &'a mut Uses,
        reserved: &'a BTreeSet<String>,
        receiver: &'a str,
    ) -> Self {
        Self {
            ir: emit.ir,
            emit,
            command,
            storages,
            uses,
            lines: Lines::new(1),
            reserved,
            receiver,
            locals: Locals::new(reserved),
            next: 0,
        }
    }

    /// A fresh temporary named from `base`.
    fn temp(&mut self, base: &str) -> String {
        let candidate = format!("{base}{}", self.next);
        self.next += 1;
        fresh(self.reserved, &candidate)
    }

    /// The method, whole.
    fn method(&mut self) -> String {
        let command = self.command;
        let method = self.emit.layout.declared(&command.name).to_owned();
        let input = self.emit.reference(&command.name);
        let outcome = self.emit.reference_outcome(&command.name);
        let unmet = self.emit.unmet();
        self.body();
        let receiver = self.receiver;
        format!(
            "\n// {method} is `{}`, generated: every outcome is one the specification fully \
             determines.\nfunc ({receiver} *Generated) {method}({} {input}) ({outcome}, {unmet}) \
             {{\n{}}}\n",
            command.name,
            self.locals.input,
            self.lines.text()
        )
    }

    /// The method body: selection in the precedence order, then the branch taken.
    // The precedence order, step by step, in the order it is evaluated.
    #[allow(clippy::too_many_lines)]
    fn body(&mut self) {
        let command = self.command;
        for outcome in &command.outcomes {
            if let (ResolvedCondition::When { predicate }, Some(_), None) =
                (&outcome.condition, &outcome.error, &outcome.subject)
            {
                self.lines.push(&format!(
                    "// `{}`: an input-guarded refusal, before anything else is read.",
                    outcome.name
                ));
                let truth = self.predicate(&Env::Input(command), predicate, "");
                self.decided(&truth, |writer| {
                    let answer = writer.variant(outcome, Held::None, None);
                    writer.lines.push(&format!("return {answer}, nil"));
                });
            }
        }
        if let Some(existing) = determined::existing_instance(command) {
            self.existing_lookup(existing);
        }
        let guarded = determined::subject_guarded(command);
        let held = if guarded {
            let subject = determined::selection_subject(command)
                .expect("a subject-guarded command the plan generates reads one subject");
            let entity = self.ir.entity(&subject.entity);
            let identity = self.input_member(&subject.instance.field().name);
            self.lines
                .push("// The addressed row, read before the branches that select by it.");
            self.get(entity, &identity);
            self.lines.open(&format!("if !{} {{", self.locals.found));
            self.unknown_arm();
            self.lines.close("}");
            self.lines.push(&format!("_ = {}", self.locals.held));
            for outcome in &command.outcomes {
                if !Self::is_subject_guard(outcome) {
                    continue;
                }
                self.lines.push(&format!(
                    "// `{}`: selected by the addressed row.",
                    outcome.name
                ));
                let truth = self.subject_guard(outcome, entity);
                self.decided(&truth, |writer| writer.take(outcome, Held::Selected));
            }
            Held::Selected
        } else {
            Held::None
        };
        for outcome in &command.outcomes {
            match &outcome.condition {
                ResolvedCondition::When { predicate } if outcome.error.is_none() => {
                    self.lines.push(&format!(
                        "// `{}`: an accepting branch, in declaration order.",
                        outcome.name
                    ));
                    let truth = self.predicate(&Env::Input(command), predicate, "");
                    self.decided(&truth, |writer| writer.take(outcome, held));
                }
                ResolvedCondition::External { .. } => {
                    self.lines.push(&format!(
                        "// `{}`: an external branch, where the context takes it.",
                        outcome.name
                    ));
                    let ask = self.external(outcome);
                    self.lines.open(&format!("if {ask} {{"));
                    self.take(outcome, held);
                    self.lines.close("}");
                }
                ResolvedCondition::ExternalWhen { predicate, .. } => {
                    self.lines.push(&format!(
                        "// `{}`: an external branch, where the context takes it and its input is \
                         eligible.",
                        outcome.name
                    ));
                    let ask = self.external(outcome);
                    self.lines.open(&format!("if {ask} {{"));
                    let truth = self.predicate(&Env::Input(command), predicate, "");
                    self.decided(&truth, |writer| writer.take(outcome, held));
                    self.lines.close("}");
                }
                _ => {}
            }
        }
        if let Some(default) = command
            .outcomes
            .iter()
            .find(|outcome| outcome.condition == ResolvedCondition::Otherwise)
        {
            self.lines
                .push(&format!("// `{}`: the default.", default.name));
            if guarded {
                // Its own block: the branch reads the row again under the names the selection
                // already declared.
                self.lines.open("{");
                self.take(default, held);
                self.lines.close("}");
            } else {
                self.take(default, held);
            }
        } else {
            self.uses.helpers.insert("undeclared");
            self.lines
                .push("// No declared branch answers this request.");
            self.lines.push(&format!(
                "return nil, undeclared({})",
                go_string(&command.name.to_string())
            ));
        }
    }

    /// `true` for a branch that selects by the addressed row.
    fn is_subject_guard(outcome: &ResolvedOutcome) -> bool {
        matches!(
            outcome.condition,
            ResolvedCondition::SubjectField { .. }
                | ResolvedCondition::SubjectPredicate { .. }
                | ResolvedCondition::SubjectState { .. }
                | ResolvedCondition::StateChange { .. }
        )
    }

    /// The guard's reading held in a temporary, an unknown one refused, and `then` written where it
    /// holds.
    fn decided(&mut self, truth: &str, then: impl FnOnce(&mut Self)) {
        self.uses.helpers.insert("undeclared");
        self.uses.helpers.insert("truth");
        let reading = self.temp("g");
        self.lines.push(&format!("{reading} := {truth}"));
        self.lines.open(&format!("if {reading} == unknown {{"));
        self.lines.push(&format!(
            "return nil, undeclared({})",
            go_string(&self.command.name.to_string())
        ));
        self.lines.close("}");
        self.lines.open(&format!("if {reading} == verity {{"));
        then(self);
        self.lines.close("}");
    }

    /// The input struct's member `field`, as an expression.
    fn input_member(&self, field: &str) -> String {
        format!(
            "{}.{}",
            self.locals.input,
            items::member_ident(&self.command.input, field)
        )
    }

    /// The Go member of an entity's data struct.
    fn data_member(entity: &ResolvedEntity, field: &str) -> String {
        super::invariant::data_member(entity, field)
    }

    /// `held, found := <storage>.Get(<identity>)`.
    fn get(&mut self, entity: &ResolvedEntity, identity: &str) {
        let storage = self.storage(&entity.name);
        let (held, found) = (&self.locals.held, &self.locals.found);
        self.lines.push(&format!(
            "{held}, {found} := {}.ports.{storage}.Get({identity})",
            self.receiver
        ));
    }

    /// The `existing_instance:` refusal, answered for an identity a record already carries
    /// (beyond10x/ess#310).
    fn existing_lookup(&mut self, existing: &ResolvedOutcome) {
        let command = self.command;
        let (creation, (field, optional)) = command
            .outcomes
            .iter()
            .find_map(|outcome| {
                determined::identity_input(outcome).map(|identity| (outcome, identity))
            })
            .expect("the plan admits `existing_instance:` beside a creation read from the input");
        let entity = &creation
            .subject
            .as_ref()
            .expect("a creation names its subject")
            .entity;
        let ir = self.ir;
        let storage = self.storage(&ir.entity(entity).name);
        let field = self.input_member(field);
        let found = self.locals.found.clone();
        self.lines.push(&format!(
            "// `{}`: an identity a record already carries, before any branch is taken.",
            existing.name
        ));
        let receiver = self.receiver;
        if optional {
            self.lines.open(&format!("if {field} != nil {{"));
            self.lines.open(&format!(
                "if _, {found} := {receiver}.ports.{storage}.Get(*{field}); {found} {{"
            ));
        } else {
            self.lines.open(&format!(
                "if _, {found} := {receiver}.ports.{storage}.Get({field}); {found} {{"
            ));
        }
        let answer = self.variant(existing, Held::None, None);
        self.lines.push(&format!("return {answer}, nil"));
        self.lines.close("}");
        if optional {
            self.lines.close("}");
        }
    }

    /// The storage field of an entity, recorded as used.
    fn storage(&mut self, entity: &QualifiedName) -> String {
        self.uses.storages.insert(entity.clone());
        self.storages[entity].clone()
    }

    /// Asks the context whether an external branch is taken.
    fn external(&mut self, outcome: &ResolvedOutcome) -> String {
        self.uses.external = true;
        format!(
            "{}.ports.Context.External({}, {})",
            self.receiver,
            go_string(&self.command.name.to_string()),
            go_string(outcome.name.as_str())
        )
    }

    /// The reading of a branch that selects by the addressed row.
    fn subject_guard(&mut self, outcome: &ResolvedOutcome, entity: &ResolvedEntity) -> String {
        let command = self.command;
        let states =
            |writer: &mut Self,
             states: &mut dyn Iterator<Item = &ess_domain::entity::StateName>| {
                writer.uses.helpers.insert("truth");
                let reading = writer.temp("s");
                let variants: Vec<String> = states
                    .map(|state| {
                        writer
                            .emit
                            .reference_variant(entity.state_type.name(), state.as_str())
                    })
                    .collect();
                writer.lines.push(&format!("{reading} := falsity"));
                writer
                    .lines
                    .push(&format!("switch {}.State.(type) {{", writer.locals.held));
                writer.lines.push(&format!("case {}:", variants.join(", ")));
                writer.lines.push(&format!("\t{reading} = verity"));
                writer.lines.push("}");
                reading
            };
        let (row, input) = match &outcome.condition {
            ResolvedCondition::SubjectField {
                field,
                equals,
                predicate,
            } => {
                let path = ess_primitives::facts::FactPath::new(field)
                    .expect("the compiler admitted the field");
                let compare = Predicate::Compare {
                    left: Operand::Fact(path),
                    op: CompareOp::Eq,
                    right: Operand::Literal(FactValue::Text(equals.clone())),
                };
                let held = self.locals.held.clone();
                (
                    self.predicate(&Env::Subject(command, entity), &compare, &held),
                    predicate.as_ref(),
                )
            }
            ResolvedCondition::SubjectPredicate { predicate, input } => {
                let held = self.locals.held.clone();
                (
                    self.predicate(&Env::Subject(command, entity), predicate, &held),
                    input.as_ref(),
                )
            }
            ResolvedCondition::SubjectState { state, predicate } => {
                (states(self, &mut state.iter()), predicate.as_ref())
            }
            ResolvedCondition::StateChange {
                states: held,
                predicate,
                ..
            } => (states(self, &mut held.iter()), predicate.as_ref()),
            _ => unreachable!("only a subject guard selects by the addressed row"),
        };
        match input {
            Some(input) => {
                self.uses.helpers.insert("allOf");
                let input = self.predicate(&Env::Input(command), input, "");
                format!("allOf({row}, {input})")
            }
            None => row,
        }
    }

    /// The statements answering an identity no record carries, ending in a `return`: the creation
    /// of create-or-update where the command declares one (beyond10x/ess#310), else the answer.
    fn unknown_arm(&mut self) {
        let command = self.command;
        if let Some(creation) = command
            .outcomes
            .iter()
            .find(|outcome| determined::creates_unknown(outcome))
        {
            self.create(creation, Held::None);
            return;
        }
        let answer = self.unknown_answer();
        self.lines.push(&format!("return {answer}"));
    }

    /// The answer for an identity no record carries, as the `return`'s two results.
    fn unknown_answer(&mut self) -> String {
        let command = self.command;
        if let Some(declared) = command
            .outcomes
            .iter()
            .find(|outcome| outcome.condition == ResolvedCondition::UnknownInstance)
        {
            return format!("{}, nil", self.variant(declared, Held::None, None));
        }
        if ess_gen::unknown_instance::unknown_instance_answer(self.ir, command).is_some() {
            return format!(
                "{}{{}}, nil",
                self.emit.reference_unknown_instance_variant(&command.name)
            );
        }
        if let Some(declared) = determined::unknown_answer(command) {
            format!("{}, nil", self.variant(declared, Held::None, None))
        } else {
            self.uses.helpers.insert("undeclared");
            format!("nil, undeclared({})", go_string(&command.name.to_string()))
        }
    }

    /// The statements of a creation, ending in its `return`.
    fn create(&mut self, outcome: &ResolvedOutcome, held: Held) {
        let subject = outcome
            .subject
            .as_ref()
            .expect("a creation names its subject");
        let entity = self.ir.entity(&subject.entity);
        let storage = self.storage(&entity.name);
        let assigned = match determined::identity_source(outcome) {
            Some(source) => self.value(source, None),
            None => self.generate(&entity.identity.type_ref),
        };
        let identity = self.locals.identity.clone();
        self.lines.push(&format!("{identity} := {assigned}"));
        let mut fields = vec![format!(
            "{}: {identity}",
            Self::data_member(entity, &entity.identity.name)
        )];
        for field in &entity.fields {
            let value = match outcome.sets.iter().find(|set| set.target == field.name) {
                Some(set) => self.value(set, None),
                None => "nil".to_owned(),
            };
            fields.push(format!(
                "{}: {value}",
                Self::data_member(entity, &field.name)
            ));
        }
        let data_type = self.emit.qualify(
            self.emit.layout.package_of(&entity.name),
            self.emit.layout.data(&entity.name),
        );
        let data = self.locals.data.clone();
        self.lines
            .push(&format!("{data} := {data_type}{{{}}}", fields.join(", ")));
        self.invariant_check(entity, &data);
        let state = subject
            .into
            .clone()
            .unwrap_or_else(|| entity.lifecycle.initial.clone());
        let snapshot = if state == entity.lifecycle.initial {
            format!(
                "{}({data}).Snapshot()",
                self.emit.qualify(
                    self.emit.layout.package_of(&entity.name),
                    self.emit.layout.ctor(&entity.name)
                )
            )
        } else {
            format!(
                "{}{{State: {}{{}}, Data: {data}}}",
                self.emit.qualify(
                    self.emit.layout.package_of(&entity.name),
                    self.emit.layout.snapshot(&entity.name)
                ),
                self.emit
                    .reference_variant(entity.state_type.name(), state.as_str())
            )
        };
        self.lines.push(&format!(
            "{}.ports.{storage}.Put({snapshot})",
            self.receiver
        ));
        let answer = self.variant(outcome, held, Some(&identity));
        self.lines.push(&format!("return {answer}, nil"));
    }

    /// The answer for a move from a state it does not start in, as the `return`'s two results.
    fn wrong_state_answer(&mut self) -> String {
        let command = self.command;
        if let Some(declared) = command
            .outcomes
            .iter()
            .find(|outcome| outcome.condition == ResolvedCondition::WrongState)
        {
            format!("{}, nil", self.variant(declared, Held::WrongState, None))
        } else {
            self.uses.helpers.insert("undeclared");
            format!("nil, undeclared({})", go_string(&command.name.to_string()))
        }
    }

    /// The statements taking one selected branch, each path ending in a `return`.
    // One arm per effect, each ending in the answer it takes.
    #[allow(clippy::too_many_lines)]
    fn take(&mut self, outcome: &ResolvedOutcome, held: Held) {
        let Some(subject) = &outcome.subject else {
            let answer = self.variant(outcome, held, None);
            self.lines.push(&format!("return {answer}, nil"));
            return;
        };
        let entity = self.ir.entity(&subject.entity);
        match (&subject.effect, &subject.instance) {
            (ResolvedEffect::Creates, ResolvedInstance::Observed { .. }) => {
                self.create(outcome, held);
            }
            (effect, ResolvedInstance::Supplied { field }) => {
                let identity = self.input_member(&field.name);
                self.get(entity, &identity);
                self.lines.open(&format!("if !{} {{", self.locals.found));
                self.unknown_arm();
                self.lines.close("}");
                let held_row = self.locals.held.clone();
                self.lines.push(&format!("_ = {held_row}"));
                let storage = self.storage(&entity.name);
                let receiver = self.receiver;
                let reads_before = outcome_reads_before(outcome);
                let before = self.locals.before.clone();
                match effect {
                    ResolvedEffect::Moves { transition } => {
                        let wrong_reads = self.wrong_state_reads(entity);
                        if wrong_reads.0 {
                            let held_state = self.locals.held_state.clone();
                            self.lines
                                .push(&format!("{held_state} := {held_row}.State"));
                        }
                        if reads_before || wrong_reads.1 {
                            self.lines.push(&format!("{before} := {held_row}.Data"));
                        }
                        let any = self.emit.qualify(
                            self.emit.layout.package_of(&entity.name),
                            self.emit.layout.any(&entity.name),
                        );
                        let (refined, moved, instance) = (
                            self.locals.refined.clone(),
                            self.locals.moved.clone(),
                            self.locals.instance.clone(),
                        );
                        self.lines
                            .push(&format!("{refined}, _ := {held_row}.Refine()"));
                        self.lines.push(&format!("var {moved} {any}"));
                        self.lines
                            .push(&format!("switch {instance} := {refined}.(type) {{"));
                        for from in &transition.from {
                            let state = self.emit.qualify(
                                self.emit.layout.package_of(&entity.name),
                                self.emit.layout.state(&entity.name, from.as_str()),
                            );
                            self.lines.push(&format!("case {state}:"));
                            self.lines.push(&format!(
                                "\t{moved} = {instance}.{}()",
                                name::exported(&transition.name)
                            ));
                        }
                        self.lines.push("default:");
                        self.lines.indent();
                        let wrong = self.wrong_state_answer();
                        self.lines.push(&format!("return {wrong}"));
                        self.lines.close("}");
                        self.write_sets(outcome, &format!("{moved}.Snapshot()"), entity);
                        let next = self.locals.next.clone();
                        self.lines
                            .push(&format!("{receiver}.ports.{storage}.Put({next})"));
                    }
                    ResolvedEffect::Updates | ResolvedEffect::Preserves => {
                        if reads_before {
                            self.lines.push(&format!("{before} := {held_row}.Data"));
                        }
                        let writes =
                            matches!(effect, ResolvedEffect::Updates) || !outcome.sets.is_empty();
                        if writes {
                            self.write_sets(outcome, &held_row, entity);
                            let next = self.locals.next.clone();
                            self.lines
                                .push(&format!("{receiver}.ports.{storage}.Put({next})"));
                        }
                    }
                    ResolvedEffect::Deletes => {
                        if reads_before {
                            self.lines.push(&format!("{before} := {held_row}.Data"));
                        }
                        self.lines
                            .push(&format!("{receiver}.ports.{storage}.Delete({identity})"));
                    }
                    ResolvedEffect::Creates => {
                        unreachable!("a creation whose identity is supplied is an obligation")
                    }
                }
                let answer = self.variant(outcome, held, None);
                self.lines.push(&format!("return {answer}, nil"));
            }
            (_, ResolvedInstance::Observed { .. }) => {
                unreachable!("an observed identity outside `creates:` is an obligation")
            }
        }
    }

    /// Whether the wrong-state answer reads the held state, and whether it reads stored fields.
    fn wrong_state_reads(&self, entity: &ResolvedEntity) -> (bool, bool) {
        let Some(declared) = self
            .command
            .outcomes
            .iter()
            .find(|outcome| outcome.condition == ResolvedCondition::WrongState)
        else {
            return (false, false);
        };
        let Some(error) = &declared.error else {
            return (false, false);
        };
        let mut reads = (false, false);
        for field in &self.ir.error(error).fields {
            if let Some(source) = declared
                .error_payload
                .iter()
                .find(|source| source.target == field.name)
            {
                reads.1 |= reads_subject(&source.value);
                continue;
            }
            match determined::held_field(entity, field) {
                Some(HeldField::State) => reads.0 = true,
                Some(HeldField::Field(_)) => reads.1 = true,
                None => {}
            }
        }
        reads
    }

    /// `next := <from>`, the branch's `sets:`, and the invariant check.
    fn write_sets(&mut self, outcome: &ResolvedOutcome, from: &str, entity: &ResolvedEntity) {
        let next = self.locals.next.clone();
        self.lines.push(&format!("{next} := {from}"));
        let before = self.locals.before.clone();
        for set in &outcome.sets {
            let value = self.value(set, Some((&before, entity)));
            self.lines.push(&format!(
                "{next}.Data.{} = {value}",
                Self::data_member(entity, &set.target)
            ));
        }
        self.invariant_check(entity, &format!("{next}.Data"));
    }

    /// The entity invariant check before a write, where the entity declares any.
    fn invariant_check(&mut self, entity: &ResolvedEntity, data: &str) {
        if entity.invariants.is_empty() {
            return;
        }
        let (broken, breaks) = (self.locals.broken.clone(), self.locals.breaks.clone());
        let obligation = self
            .emit
            .qualify(self.emit.layout.obligation(), "UnmetObligation");
        self.lines.open(&format!(
            "if {broken}, {breaks} := {data}.BrokenInvariant(); {breaks} {{"
        ));
        self.lines.push(&format!(
            "return nil, &{obligation}{{Capability: \"entity invariant\", Source: {broken}}}"
        ));
        self.lines.close("}");
    }

    /// The outcome variant, with its events and error, as an expression.
    fn variant(&mut self, outcome: &ResolvedOutcome, held: Held, created: Option<&str>) -> String {
        let command = self.command;
        let variant = self
            .emit
            .reference_outcome_variant(&command.name, outcome.name.as_str());
        let carried = items::outcome_event_fields(self.emit, outcome);
        if carried.is_empty() && outcome.error.is_none() {
            return format!("{variant}{{}}");
        }
        let mut members = Vec::new();
        for field in carried {
            let event = self.event(outcome, field.event, created);
            members.push(format!("{}: {event}", field.field));
        }
        if let Some(error) = &outcome.error {
            let declared = self.ir.error(error);
            let path = self.emit.reference(error.name());
            if declared.fields.is_empty() {
                members.push(format!("Error: {path}{{}}"));
            } else {
                let entity = match held {
                    Held::Selected => determined::selection_subject(command)
                        .map(|subject| self.ir.entity(&subject.entity)),
                    Held::WrongState => determined::wrong_state_entity(self.ir, command),
                    Held::None => None,
                };
                let held_data = format!("{}.Data", self.locals.held);
                let row = match held {
                    Held::Selected => Some(held_data.as_str()),
                    Held::WrongState => Some(self.locals.before.as_str()),
                    Held::None => None,
                }
                .map(ToOwned::to_owned);
                let mut fields = Vec::new();
                for field in &declared.fields {
                    let member = items::member_ident(&declared.fields, &field.name);
                    if let Some(source) = outcome
                        .error_payload
                        .iter()
                        .find(|source| source.target == field.name)
                    {
                        let value = self.value(source, row.as_deref().zip(entity));
                        fields.push(format!("{member}: {value}"));
                        continue;
                    }
                    let entity =
                        entity.expect("an error field with no source is answered from a held row");
                    let value = match (
                        determined::held_field(entity, field)
                            .expect("the plan admitted only held error fields"),
                        held,
                    ) {
                        (HeldField::State, Held::WrongState) => self.locals.held_state.clone(),
                        (HeldField::State, _) => format!("{}.State", self.locals.held),
                        (HeldField::Field(stored), Held::WrongState) => format!(
                            "{}.{}",
                            self.locals.before,
                            Self::data_member(entity, &stored.name)
                        ),
                        (HeldField::Field(stored), _) => format!(
                            "{}.Data.{}",
                            self.locals.held,
                            Self::data_member(entity, &stored.name)
                        ),
                    };
                    fields.push(format!("{member}: {value}"));
                }
                members.push(format!("Error: {path}{{{}}}", fields.join(", ")));
            }
        }
        format!("{variant}{{{}}}", members.join(", "))
    }

    /// One emitted event, every field filled.
    fn event(
        &mut self,
        outcome: &ResolvedOutcome,
        event: &ess_compiler::ir::EventHandle,
        created: Option<&str>,
    ) -> String {
        let declared = self.ir.event(event);
        let path = self.emit.reference(event.name());
        if declared.fields.is_empty() {
            return format!("{path}{{}}");
        }
        let determined = outcome
            .payload
            .iter()
            .find(|payload| &payload.event == event);
        let instance = outcome
            .subject
            .as_ref()
            .and_then(|subject| match &subject.instance {
                ResolvedInstance::Observed {
                    event: published,
                    field,
                } if published == event => Some(field.name.clone()),
                _ => None,
            });
        let before_entity = outcome
            .subject
            .as_ref()
            .filter(|subject| !matches!(subject.effect, ResolvedEffect::Creates))
            .map(|subject| self.ir.entity(&subject.entity));
        let before = self.locals.before.clone();
        let mut fields = Vec::new();
        for field in &declared.fields {
            let source = determined
                .and_then(|payload| payload.fields.iter().find(|it| it.target == field.name));
            let value = match (
                instance.as_deref() == Some(field.name.as_str()),
                created,
                source,
            ) {
                (true, Some(created), _) => created.to_owned(),
                (_, _, Some(source)) => self.value(
                    source,
                    before_entity.map(|entity| (before.as_str(), entity)),
                ),
                (_, _, None) => self.assigned(&field.type_ref),
            };
            fields.push(format!(
                "{}: {value}",
                items::member_ident(&declared.fields, &field.name)
            ));
        }
        format!("{path}{{{}}}", fields.join(", "))
    }

    /// A value the implementation assigns: absent where optional, else from the context.
    fn assigned(&mut self, target: &ResolvedTypeRef) -> String {
        if target.is_optional() {
            "nil".to_owned()
        } else {
            self.generate(target)
        }
    }

    /// `<receiver>.ports.Context.Generate<Type>()`, recorded on the context, as a temporary.
    fn generate(&mut self, target: &ResolvedTypeRef) -> String {
        let method = format!("Generate{}", name::type_fragment(&target.to_string()));
        self.uses.generates.insert(
            method.clone(),
            (self.emit.go_type(target), target.to_string()),
        );
        let minted = self.temp("m");
        self.lines.push(&format!(
            "{minted} := {}.ports.Context.{method}()",
            self.receiver
        ));
        minted
    }

    /// `some(<expression>)`.
    fn some(&mut self, expression: &str) -> String {
        self.uses.helpers.insert("some");
        format!("some({expression})")
    }

    /// The value one source fills its field with. `before` names the held data before the outcome
    /// and its entity, where the branch holds a row.
    // One arm per value source the model declares, each rendering its own expression.
    #[allow(clippy::too_many_lines)]
    fn value(
        &mut self,
        field: &ResolvedPayloadField,
        before: Option<(&str, &ResolvedEntity)>,
    ) -> String {
        let target = &field.target_type;
        match &field.value {
            ResolvedPayloadValue::InputField {
                field: source,
                type_ref,
            } => {
                let read = self.input_member(source);
                if type_ref == target {
                    read
                } else {
                    self.some(&read)
                }
            }
            ResolvedPayloadValue::SubjectField {
                field: source,
                type_ref,
            } => {
                let (row, entity) =
                    before.expect("the plan admits `{subject:}` only where a row is held");
                let read = format!("{row}.{}", Self::data_member(entity, source));
                if type_ref == target {
                    read
                } else {
                    self.some(&read)
                }
            }
            ResolvedPayloadValue::CallerAttribute {
                attribute,
                type_ref,
            } => {
                let method = self.caller(attribute, type_ref);
                let receiver = self.receiver;
                if type_ref == target {
                    self.uses.helpers.insert("undeclared");
                    let (value, ok) = (self.temp("c"), self.temp("ok"));
                    self.lines.push(&format!(
                        "{value}, {ok} := {receiver}.ports.Context.{method}()"
                    ));
                    self.lines.open(&format!("if !{ok} {{"));
                    self.lines.push(&format!(
                        "return nil, undeclared({})",
                        go_string(&self.command.name.to_string())
                    ));
                    self.lines.close("}");
                    value
                } else {
                    self.uses.helpers.insert("present");
                    let value = self.temp("c");
                    self.lines.push(&format!(
                        "{value} := present({receiver}.ports.Context.{method}())"
                    ));
                    value
                }
            }
            ResolvedPayloadValue::Literal { value } => self.literal(target, value),
            ResolvedPayloadValue::Generated => self.assigned(target),
            ResolvedPayloadValue::Cleared => "nil".to_owned(),
            ResolvedPayloadValue::Increment { by } => {
                let (row, entity) =
                    before.expect("the plan admits `{increment:}` only on a held row");
                let read = format!("{row}.{}", Self::data_member(entity, &field.target));
                self.increment(target, &read, by)
            }
            ResolvedPayloadValue::InputOrGenerated {
                field: source,
                otherwise,
                ..
            } => {
                let read = self.input_member(source);
                if target.is_optional() && otherwise.is_none() {
                    return read;
                }
                let required = target.required().clone();
                let chosen = self.temp("v");
                let go_type = self.emit.go_type(&required);
                self.lines.push(&format!("var {chosen} {go_type}"));
                self.lines.open(&format!("if {read} != nil {{"));
                self.lines.push(&format!("{chosen} = *{read}"));
                self.lines.close("} else {");
                self.lines.indent();
                let fallback = match otherwise {
                    Some(text) => self.literal(&required, text),
                    None => self.generate(&required),
                };
                self.lines.push(&format!("{chosen} = {fallback}"));
                self.lines.close("}");
                if target.is_optional() {
                    self.some(&chosen)
                } else {
                    chosen
                }
            }
            ResolvedPayloadValue::Struct { fields } => {
                let ResolvedTypeRef::Declared { name: declared } = target.required() else {
                    unreachable!("the plan admits a struct source only for a struct")
                };
                let ResolvedBody::Struct {
                    fields: members, ..
                } = &self.ir.named_type(declared).body
                else {
                    unreachable!("the plan admits a struct source only for a struct")
                };
                let mut rendered = Vec::new();
                for member in members {
                    let value = match fields.iter().find(|source| source.target == member.name) {
                        Some(source) => self.value(source, before),
                        None => "nil".to_owned(),
                    };
                    rendered.push(format!(
                        "{}: {value}",
                        items::member_ident(members, &member.name)
                    ));
                }
                let built = format!(
                    "{}{{{}}}",
                    self.emit.reference(declared.name()),
                    rendered.join(", ")
                );
                if target.is_optional() {
                    self.some(&built)
                } else {
                    built
                }
            }
            ResolvedPayloadValue::RelatedField { .. }
            | ResolvedPayloadValue::ChangedCount
            | ResolvedPayloadValue::ResponseField { .. } => {
                unreachable!("the plan keeps this source's command an obligation")
            }
        }
    }

    /// The context method reading one caller attribute, recorded on the context.
    fn caller(&mut self, attribute: &str, type_ref: &ResolvedTypeRef) -> String {
        caller_method(self.emit, self.uses, attribute, type_ref)
    }

    /// A literal the model writes, as a value of `target`.
    fn literal(&mut self, target: &ResolvedTypeRef, text: &str) -> String {
        match target {
            ResolvedTypeRef::Optional { of } => {
                let inner = self.literal(of, text);
                self.some(&inner)
            }
            ResolvedTypeRef::Primitive { name } => match name {
                Primitive::Integer => format!("int64({text})"),
                Primitive::Boolean => text.to_owned(),
                Primitive::String => go_string(text),
                Primitive::Decimal
                | Primitive::Uuid
                | Primitive::Timestamp
                | Primitive::Duration => {
                    format!("{}({})", self.emit.primitive_ctor(*name), go_string(text))
                }
                _ => unreachable!("the plan admits literals of these primitives only"),
            },
            ResolvedTypeRef::Declared { name } => match &self.ir.named_type(name).body {
                ResolvedBody::Newtype { of, .. } => {
                    let inner = self.literal(of, text);
                    format!("{}({inner})", self.emit.reference_ctor(name.name()))
                }
                ResolvedBody::Enum { .. } => {
                    format!("{}{{}}", self.emit.reference_variant(name.name(), text))
                }
                _ => unreachable!("the plan admits literals of scalars only"),
            },
            _ => unreachable!("the plan admits literals of scalars only"),
        }
    }

    /// The previous value of `read` plus `by`, through the newtypes of `target`.
    fn increment(&mut self, target: &ResolvedTypeRef, read: &str, by: &str) -> String {
        match target {
            ResolvedTypeRef::Primitive { .. } => format!("{read} + {by}"),
            ResolvedTypeRef::Declared { name } => match &self.ir.named_type(name).body {
                ResolvedBody::Newtype { of, .. } => {
                    let inner = self.increment(of, &format!("{read}.Value()"), by);
                    format!("{}({inner})", self.emit.reference_ctor(name.name()))
                }
                _ => unreachable!("the plan admits `{{increment:}}` of an Integer only"),
            },
            _ => unreachable!("the plan admits `{{increment:}}` of an Integer only"),
        }
    }

    /// A predicate as a `truth` expression, its reads written before it.
    fn predicate(&mut self, env: &Env<'_>, predicate: &Predicate, row: &str) -> String {
        let mut guards = Guards {
            ir: self.ir,
            emit: self.emit,
            uses: &mut *self.uses,
            lines: &mut self.lines,
            reserved: self.reserved,
            next: &mut self.next,
            receiver: self.receiver,
            row: row.to_owned(),
            input: self.locals.input.clone(),
            command: Some(self.command),
            row_entity: match env {
                Env::Subject(_, entity) | Env::Row(entity) => Some(*entity),
                Env::Input(_) => None,
            },
        };
        guards.predicate(env, predicate)
    }
}

/// `true` where the branch reads the held row as it was before the outcome.
fn outcome_reads_before(outcome: &ResolvedOutcome) -> bool {
    outcome.sets.iter().any(|set| reads_subject(&set.value))
        || outcome
            .payload
            .iter()
            .flat_map(|payload| &payload.fields)
            .any(|field| reads_subject(&field.value))
}

/// Whether one value source reads the row as it was before the outcome.
fn reads_subject(value: &ResolvedPayloadValue) -> bool {
    match value {
        ResolvedPayloadValue::SubjectField { .. } | ResolvedPayloadValue::Increment { .. } => true,
        ResolvedPayloadValue::Struct { fields } => {
            fields.iter().any(|field| reads_subject(&field.value))
        }
        _ => false,
    }
}

/// The context method reading one caller attribute, recorded on the context.
fn caller_method(
    emit: &Emit<'_>,
    uses: &mut Uses,
    attribute: &str,
    type_ref: &ResolvedTypeRef,
) -> String {
    let method = name::exported(&format!("caller_{attribute}"));
    uses.callers.insert(
        method.clone(),
        (emit.go_type(type_ref), attribute.to_owned()),
    );
    method
}

// ---- guards --------------------------------------------------------------------------------------

/// One step a read takes only where it finds something: the condition, and what it binds.
struct Guard {
    condition: String,
    bind: Option<(String, String)>,
}

/// Renders a guard — a command's, or a view's `filter:` — as a `truth` expression, writing the
/// statements its reads need before it and recording what it asks of the ports and the helpers.
struct Guards<'a, 'w> {
    ir: &'a EssIr,
    emit: &'a Emit<'a>,
    uses: &'w mut Uses,
    lines: &'w mut Lines,
    reserved: &'a BTreeSet<String>,
    next: &'w mut usize,
    receiver: &'a str,
    /// The variable a stored field or `state` is read from: a snapshot.
    row: String,
    /// The command's input parameter.
    input: String,
    /// The command whose input and caller a path may read.
    command: Option<&'a ResolvedCommand>,
    /// The entity a stored field or `state` is read from.
    row_entity: Option<&'a ResolvedEntity>,
}

impl Guards<'_, '_> {
    /// A fresh temporary named from `base`.
    fn temp(&mut self, base: &str) -> String {
        let candidate = format!("{base}{}", self.next);
        *self.next += 1;
        fresh(self.reserved, &candidate)
    }

    /// A predicate as a `truth` expression.
    fn predicate(&mut self, env: &Env<'_>, predicate: &Predicate) -> String {
        self.uses.helpers.insert("truth");
        match predicate {
            Predicate::Always => "verity".to_owned(),
            Predicate::Never => "falsity".to_owned(),
            Predicate::All(children) | Predicate::Any(children) => {
                let helper = if matches!(predicate, Predicate::All(_)) {
                    "allOf"
                } else {
                    "anyOf"
                };
                self.uses.helpers.insert(helper);
                let rendered: Vec<String> = children
                    .iter()
                    .map(|child| self.predicate(env, child))
                    .collect();
                format!("{helper}({})", rendered.join(", "))
            }
            Predicate::Not(child) => {
                self.uses.helpers.insert("not");
                format!("not({})", self.predicate(env, child))
            }
            Predicate::Defined(path) => self.defined(env, path),
            Predicate::Truthy(path) => {
                let resolved = self.resolve(env, path);
                let read = self.read(&resolved);
                self.uses.helpers.insert("truthOf");
                format!("truthOf({read})")
            }
            Predicate::Compare { left, op, right } => {
                let kind = [left, right]
                    .into_iter()
                    .find_map(|operand| match operand {
                        Operand::Fact(path) => Some(self.resolve(env, path).kind),
                        Operand::Literal(_) => None,
                    })
                    .expect("the plan admits comparisons reading a fact");
                let left = self.operand(env, left, &kind);
                let right = self.operand(env, right, &kind);
                if let Kind::Number(_) = kind {
                    self.uses.helpers.insert("compareNumbers");
                    let accepts = match op {
                        CompareOp::Eq => "isEq",
                        CompareOp::Ne => "isNe",
                        CompareOp::Lt => "isLt",
                        CompareOp::Le => "isLe",
                        CompareOp::Gt => "isGt",
                        CompareOp::Ge => "isGe",
                    };
                    format!("compareNumbers({left}, {right}, {accepts})")
                } else {
                    self.uses.helpers.insert("equal");
                    let equal = format!("equal({left}, {right})");
                    if *op == CompareOp::Ne {
                        self.uses.helpers.insert("not");
                        format!("not({equal})")
                    } else {
                        equal
                    }
                }
            }
            Predicate::AnyOf { path, values } | Predicate::NoneOf { path, values } => {
                let resolved = self.resolve(env, path);
                self.uses.helpers.insert("anyOf");
                self.uses.helpers.insert("equal");
                let read = self.read(&resolved);
                let checks: Vec<String> = values
                    .iter()
                    .map(|value| format!("equal({read}, {})", self.fact_literal(value)))
                    .collect();
                let any = format!("anyOf({})", checks.join(", "));
                if matches!(predicate, Predicate::NoneOf { .. }) {
                    self.uses.helpers.insert("not");
                    format!("not({any})")
                } else {
                    any
                }
            }
            Predicate::TextMatch { path, op, value } => {
                let resolved = self.resolve(env, path);
                let FactValue::Text(literal) = value else {
                    unreachable!("the plan admits text tests of text literals")
                };
                self.uses.helpers.insert("textMatch");
                let read = self.read(&resolved);
                format!(
                    "textMatch({read}, {}, {})",
                    go_string(op.keyword()),
                    go_string(literal)
                )
            }
            _ => unreachable!("the plan admits only the guards `determined::supported` names"),
        }
    }

    /// `defined(path)`: whether every step of the path found something.
    fn defined(&mut self, env: &Env<'_>, path: &ess_primitives::facts::FactPath) -> String {
        let resolved = self.resolve(env, path);
        let (guards, _, _) = self.reference(&resolved);
        if guards.is_empty() {
            return "verity".to_owned();
        }
        let reading = self.temp("t");
        self.lines.push(&format!("{reading} := falsity"));
        let depth = self.open(&guards);
        self.lines.push(&format!("{reading} = verity"));
        self.close(depth);
        reading
    }

    /// A literal operand, in the form its comparison reads.
    fn fact_literal(&mut self, value: &FactValue) -> String {
        self.uses.helpers.insert("some");
        match value {
            FactValue::Bool(value) => format!("some({value})"),
            FactValue::Number(number) => format!("some({})", go_string(&number.to_string())),
            FactValue::Text(text) => format!("some({})", go_string(text)),
        }
    }

    /// Resolves a path the plan already checked.
    fn resolve(&self, env: &Env<'_>, path: &ess_primitives::facts::FactPath) -> Resolved {
        determined::resolve(self.ir, env, path)
            .expect("the plan admitted only guards whose paths resolve")
    }

    /// One comparison operand, normalized to what the comparison reads.
    fn operand(&mut self, env: &Env<'_>, operand: &Operand, kind: &Kind) -> String {
        let _ = kind;
        match operand {
            Operand::Fact(path) => {
                let resolved = self.resolve(env, path);
                self.read(&resolved)
            }
            Operand::Literal(value) => self.fact_literal(value),
        }
    }

    /// Opens one `if` per guard; returns the depth to close back to.
    fn open(&mut self, guards: &[Guard]) -> usize {
        let depth = self.lines.depth();
        for guard in guards {
            self.lines.open(&format!("if {} {{", guard.condition));
            if let Some((bind, found)) = &guard.bind {
                self.lines.push(&format!("{bind} := {found}"));
            }
        }
        if let Some((bind, _)) = guards.last().and_then(|guard| guard.bind.as_ref()) {
            self.lines.push(&format!("_ = {bind}"));
        }
        depth
    }

    /// Closes the guards [`Self::open`] opened.
    fn close(&mut self, depth: usize) {
        while self.lines.depth() > depth {
            self.lines.close("}");
        }
    }

    /// A path as the guards it takes, the expression it ends in, and the type there.
    fn reference(&mut self, resolved: &Resolved) -> (Vec<Guard>, String, ResolvedTypeRef) {
        let mut guards = Vec::new();
        let mut expression = match &resolved.root {
            Root::Input(field) => {
                let command = self.command.expect("an input path is read in a command");
                format!(
                    "{}.{}",
                    self.input,
                    items::member_ident(&command.input, field)
                )
            }
            Root::Stored(field) => format!("{}.Data.{}", self.row, self.stored_member(field)),
            Root::State => format!("{}.State", self.row),
            Root::Caller(attribute) => {
                let method = caller_method(self.emit, self.uses, attribute, &resolved.root_type);
                let (value, ok) = (self.temp("c"), self.temp("ok"));
                self.lines.push(&format!(
                    "{value}, {ok} := {}.ports.Context.{method}()",
                    self.receiver
                ));
                let bind = self.temp("v");
                guards.push(Guard {
                    condition: ok,
                    bind: Some((bind.clone(), value)),
                });
                bind
            }
        };
        let mut current = resolved.root_type.clone();
        for step in &resolved.steps {
            match step {
                Step::Optional => {
                    let bind = self.temp("v");
                    guards.push(Guard {
                        condition: format!("{expression} != nil"),
                        bind: Some((bind.clone(), format!("*{expression}"))),
                    });
                    expression = bind;
                    if let ResolvedTypeRef::Optional { of } = current {
                        current = *of;
                    }
                }
                Step::Newtype => {
                    expression = format!("{expression}.Value()");
                    if let ResolvedTypeRef::Declared { name } = &current {
                        if let ResolvedBody::Newtype { of, .. } = &self.ir.named_type(name).body {
                            current = of.clone();
                        }
                    }
                }
                Step::Field(field) => {
                    if let ResolvedTypeRef::Declared { name } = &current {
                        if let ResolvedBody::Struct { fields, .. } = &self.ir.named_type(name).body
                        {
                            expression =
                                format!("{expression}.{}", items::member_ident(fields, field));
                            if let Some(member) = fields.iter().find(|member| &member.name == field)
                            {
                                current = member.type_ref.clone();
                            }
                        }
                    }
                }
                Step::Count => {}
            }
        }
        (guards, expression, current)
    }

    /// The Go member of the row's entity data.
    fn stored_member(&self, field: &str) -> String {
        let entity = self.row_entity();
        Writer::data_member(entity, field)
    }

    /// The entity a stored field is read from: the command's subject, or the view's source.
    fn row_entity(&self) -> &ResolvedEntity {
        self.row_entity.expect("a stored field is read from a row")
    }

    /// A path as a pointer to what its kind compares — a decimal rendering for a number, the text
    /// of a string, identity, enum or state, a Boolean — nil where it is not read.
    fn read(&mut self, resolved: &Resolved) -> String {
        self.uses.helpers.insert("some");
        let (guards, expression, current) = self.reference(resolved);
        let leaf = self.leaf(resolved, &expression, &current);
        if guards.is_empty() {
            if let ReadLeaf::Expression(value) = &leaf {
                return format!("some({value})");
            }
        }
        let go_type = if resolved.kind == Kind::Bool && resolved.steps.last() != Some(&Step::Count)
        {
            "*bool"
        } else {
            "*string"
        };
        let reading = self.temp("r");
        self.lines.push(&format!("var {reading} {go_type}"));
        let depth = self.open(&guards);
        match leaf {
            ReadLeaf::Expression(value) => self.lines.push(&format!("{reading} = some({value})")),
            ReadLeaf::Variants(arms) => {
                self.lines.push(&format!("switch {expression}.(type) {{"));
                for (variant, spelled) in arms {
                    self.lines.push(&format!("case {variant}:"));
                    self.lines
                        .push(&format!("\t{reading} = some({})", go_string(&spelled)));
                }
                self.lines.push("}");
            }
        }
        self.close(depth);
        reading
    }

    /// A path as the pointer to text an aggregate reads: [`Self::read`], with an opaque value as
    /// its rendering and a Boolean as `true` or `false`.
    fn text(&mut self, resolved: &Resolved) -> String {
        match &resolved.kind {
            Kind::Opaque => {
                self.uses.helpers.insert("some");
                let (guards, expression, _) = self.reference(resolved);
                if guards.is_empty() {
                    return format!("some({expression}.Value())");
                }
                let reading = self.temp("r");
                self.lines.push(&format!("var {reading} *string"));
                let depth = self.open(&guards);
                self.lines
                    .push(&format!("{reading} = some({expression}.Value())"));
                self.close(depth);
                reading
            }
            Kind::Bool => {
                let flag = self.read(resolved);
                let reading = self.temp("r");
                self.emit.import("strconv");
                self.lines.push(&format!("var {reading} *string"));
                self.lines.open(&format!("if {flag} != nil {{"));
                self.lines
                    .push(&format!("{reading} = some(strconv.FormatBool(*{flag}))"));
                self.lines.close("}");
                reading
            }
            _ => self.read(resolved),
        }
    }

    /// What one present value at the end of a path reads, held in `at`.
    fn leaf(&mut self, resolved: &Resolved, at: &str, current: &ResolvedTypeRef) -> ReadLeaf {
        if resolved.steps.last() == Some(&Step::Count) {
            self.emit.import("strconv");
            return ReadLeaf::Expression(format!("strconv.Itoa(len({at}))"));
        }
        match &resolved.kind {
            Kind::Number(Primitive::Decimal) => ReadLeaf::Expression(format!("{at}.Value()")),
            Kind::Number(_) => {
                self.emit.import("strconv");
                ReadLeaf::Expression(format!("strconv.FormatInt({at}, 10)"))
            }
            Kind::Text => match current {
                ResolvedTypeRef::Primitive {
                    name: Primitive::String,
                } => ReadLeaf::Expression(at.to_owned()),
                _ => ReadLeaf::Expression(format!("{at}.Value()")),
            },
            Kind::Bool => ReadLeaf::Expression(at.to_owned()),
            Kind::Enum(ResolvedTypeRef::Declared { name }, variants) => ReadLeaf::Variants(
                variants
                    .iter()
                    .map(|variant| {
                        (
                            self.emit.reference_variant(name.name(), variant),
                            variant.clone(),
                        )
                    })
                    .collect(),
            ),
            Kind::Enum(..) => unreachable!("an enum is a declared type"),
            Kind::State => {
                let ResolvedTypeRef::Declared { name: state_type } = &resolved.root_type else {
                    unreachable!("a state path starts at the lifecycle's enum")
                };
                let ResolvedBody::Enum { variants } = &self.ir.named_type(state_type).body else {
                    unreachable!("a lifecycle's state type is an enum")
                };
                ReadLeaf::Variants(
                    variants
                        .iter()
                        .map(|variant| {
                            (
                                self.emit
                                    .reference_variant(state_type.name(), variant.name()),
                                variant.name().to_owned(),
                            )
                        })
                        .collect(),
                )
            }
            Kind::Opaque => unreachable!("the plan admits no comparison of an opaque value"),
        }
    }
}

/// What one present value reads: an expression, or one arm per enum variant.
enum ReadLeaf {
    Expression(String),
    Variants(Vec<(String, String)>),
}
