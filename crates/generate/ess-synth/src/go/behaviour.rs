//! Generated behaviour for the Go target: what the specification fully determines, written against
//! generated ports — the Go rendering of [`crate::rust`]'s `behaviour` module, with its semantics
//! and its order of evaluation.
//!
//! A command the plan marks generated (`crate::determined`) and a view whose query it marks
//! generated (`crate::view_query`) get a method on `behaviour.Generated`, with the name and
//! signature of the seam its bounded context already declares, so every component port that takes
//! a behaviour bundle takes a `*Generated` unchanged. Everything the specification leaves to the
//! implementor is a port in `behaviour.Ports`: one storage interface per entity (get, put, delete
//! and, where a query reads it, list — ess generates the interface and never a store), one context
//! interface (the caller's attributes, the values the model says the implementation assigns, and
//! the answer to an `external:` branch), and `Owed`, every behaviour and query the plan still owes,
//! which `Generated` forwards to.
//!
//! # The order of evaluation
//!
//! The Rust target's, step for step (see `crate::rust`'s `behaviour` module): the input-guarded
//! refusals; the existence lookup; on a subject-guarded command the addressed row and the branches
//! that select by it; the accepting and external branches in declaration order; the default. The
//! branch taken then reads its own subject. A guard that is unknown, or a request no declared
//! branch answers, is the typed refusal naming the command.
//!
//! # What Go spells differently
//!
//! Go has no `Option` to chain and no `?`: a read that may find nothing is written as statements
//! ending in a pointer that is nil where the read found nothing, and a guard is a value of the
//! package's own three-valued `truth`. Every port call that has an effect — a minted identity, a
//! stored row — is its own statement, in the order the Rust target makes it.
//!
//! One thing Go cannot do at all: give one type two methods of one name. Two seams of the module
//! whose Go method names coincide (`alpha.Place` and `beta.Place`) cannot both be methods of
//! `Generated`; every seam of such a group stays off it, and a generated one among them keeps its
//! seam owed, with the weakening stated in `TARGET.md`.

