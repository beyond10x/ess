//! Lower the sealed recipe to Go function bindings, never a replacement runtime parser.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use super::target::Configuration;
use super::{
    target, Binary64Range, Binary64Step, Condition, Expr, IntegerOp, NumberPath, Overflow, Plan,
    Realization, Refused, Scope,
};
use crate::realize::finding;

// Frozen qualification profile, not a promise to accept future primitive-pattern changes.
const BASE64_PATTERN: &str = "^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$";

pub(super) fn generate(plan: &Plan, package: &str, module: &str) -> Result<Realization, Refused> {
    if !crate::realize::go::package_name(package)
        || package == "main"
        || !crate::realize::go::module_name(module)
    {
        return Err(Refused(vec![finding(
            "/",
            "go_configuration",
            "use a valid non-main Go package and module identity",
        )]));
    }
    check_schema_support(plan)?;
    let (roots, mut files) = target::sources(plan)?;
    let positional = plan.recipe.format == super::FORMAT_V6;
    let floating = positional || plan.recipe.format == super::FORMAT_V5;
    let capture = floating || plan.recipe.format == super::FORMAT_V4;
    for (path, source) in runtime_sources(positional, floating, capture) {
        files.insert(path.to_owned(), source.replace("__PACKAGE__", package));
    }
    if capture {
        files.insert(
            "retained.go".to_owned(),
            if positional {
                include_str!("go_retained.go.txt")
            } else {
                include_str!("legacy_v4_v5/go_retained.go.txt")
            }
            .replace("__PACKAGE__", package),
        );
    }
    files.insert("source.recipe.json".to_owned(), plan.to_json());
    files.insert("go.mod".to_owned(),format!("module {module}\n\ngo 1.26\n\nrequire (\n\tgithub.com/go-json-experiment/json v0.0.0-20260601182631-00ed12fed2a6\n\tgithub.com/santhosh-tekuri/jsonschema/v6 v6.0.2\n)\n\nrequire golang.org/x/text v0.14.0 // indirect\n"));
    files.insert("go.sum".to_owned(), include_str!("go.sum.txt").to_owned());
    let mut source = format!("// Code generated by ESS. DO NOT EDIT.\npackage {package}\n\nvar rootSources = []schemaSource{{\n");
    for root in &roots {
        writeln!(source, "{{path:{}}},", quote(&root.schema_path)).expect("String write");
    }
    source.push_str("}\n\nvar branches = map[string][]stage{\n");
    for (name, stages) in &plan.recipe.branches {
        writeln!(source, "{}: {{", quote(name)).expect("String write");
        for stage in stages {
            let input = roots
                .iter()
                .position(|root| root.identity == stage.input)
                .expect("checked root");
            let output = roots
                .iter()
                .position(|root| root.identity == stage.output)
                .expect("checked root");
            writeln!(
                source,
                "{{input:{input},output:{output},requires:[]condition{{{}}},value:{}}},",
                stage
                    .requires
                    .iter()
                    .map(condition)
                    .collect::<Vec<_>>()
                    .join(","),
                expression(&stage.value)
            )
            .expect("String write");
        }
        source.push_str("},\n");
    }
    source.push_str("}\n");
    input_paths(
        &mut source,
        "numberPaths",
        plan.recipe.binary64_inputs.as_ref(),
    );
    if capture {
        input_paths(
            &mut source,
            "capturePaths",
            plan.recipe.raw_json_inputs.as_ref(),
        );
    }
    if positional {
        positional_bindings(&mut source, plan);
    }
    files.insert("bindings.go".to_owned(), source);
    Ok(target::finish(
        plan,
        Configuration::Go {
            package: package.to_owned(),
            module: module.to_owned(),
        },
        files,
        roots,
    ))
}

fn positional_bindings(source: &mut String, plan: &Plan) {
    source.push_str("\nvar positionArities = map[string]uint64{\n");
    for (at, arity) in &plan.position_arities {
        writeln!(source, "{}: {arity},", quote(at)).expect("String write");
    }
    source.push_str("}\n\nvar positionalPolicies = map[string][]positionalPolicy{\n");
    if let Some(branches) = &plan.recipe.positional_inputs {
        for (branch, policies) in branches {
            writeln!(source, "{}: {{", quote(branch)).expect("String write");
            for policy in policies {
                write!(source, "{{length:{},path:[]numberSegment{{", policy.length)
                    .expect("String write");
                for segment in &policy.path {
                    match segment {
                        NumberPath::Field { name } => {
                            write!(source, "{{name:{}}},", quote(name))
                        }
                        NumberPath::Items => write!(source, "{{items:true}},"),
                    }
                    .expect("String write");
                }
                source.push_str("}},\n");
            }
            source.push_str("},\n");
        }
    }
    source.push_str("}\n");
}

fn input_paths(source: &mut String, name: &str, branches: Option<&super::Binary64Inputs>) {
    writeln!(source, "\nvar {name} = map[string][][]numberSegment{{").expect("String write");
    if let Some(branches) = branches {
        for (branch, paths) in branches {
            writeln!(source, "{}: {{", quote(branch)).expect("String write");
            for path in paths {
                source.push('{');
                for segment in path {
                    match segment {
                        NumberPath::Field { name } => write!(source, "{{name:{}}},", quote(name)),
                        NumberPath::Items => write!(source, "{{items:true}},"),
                    }
                    .expect("String write");
                }
                source.push_str("},\n");
            }
            source.push_str("},\n");
        }
    }
    source.push_str("}\n");
}

fn check_schema_support(plan: &Plan) -> Result<(), Refused> {
    let selected = plan
        .recipe
        .branches
        .values()
        .flatten()
        .flat_map(|stage| [&stage.input, &stage.output])
        .collect::<BTreeSet<_>>();
    let mut found = BTreeSet::new();
    for root in selected {
        let mut errors = Vec::new();
        let types =
            super::source::selection(root, &plan.bundles, &plan.models, "/roots", &mut errors)
                .ok_or_else(|| Refused(errors.clone()))?;
        if !errors.is_empty() {
            return Err(Refused(errors));
        }
        let source = match root {
            super::Root::Bundle { bundle_digest, .. } => format!("/bundles/{bundle_digest}"),
            super::Root::Model { model, .. } => format!("/models/{}", model.projection_digest),
        };
        for (pointer, pattern) in &types.patterns {
            if pattern == BASE64_PATTERN {
                continue;
            }
            found.insert(finding(
                &format!("{source}{pointer}"),
                "go_schema_pattern",
                "Go pattern semantics are not qualified against the reference ECMA-262 validator",
            ));
        }
    }
    if found.is_empty() {
        Ok(())
    } else {
        Err(Refused(found.into_iter().collect()))
    }
}

fn quote(value: &str) -> String {
    serde_json::to_string(value).expect("string serializes")
}
fn expressions(items: &[Expr]) -> String {
    items.iter().map(expression).collect::<Vec<_>>().join(",")
}

fn record(fields: &std::collections::BTreeMap<String, Expr>) -> String {
    format!(
        "recordValue([]member{{{}}})",
        fields
            .iter()
            .map(|(key, value)| format!("{{name:{},value:{}}}", quote(key), expression(value)))
            .collect::<Vec<_>>()
            .join(",")
    )
}

fn expression(value: &Expr) -> String {
    match value {
        Expr::Position { value, index } => format!("positionValue({},{index})", expression(value)),
        Expr::Null => "literal(nil)".to_owned(),
        Expr::Boolean { value } => format!("literal({value})"),
        Expr::String { value } => format!("literal({})", quote(value)),
        Expr::Integer { value } => format!("literal(int64({value}))"),
        Expr::Binary64Literal { value } => floating_literal(value),
        Expr::Binary64 { value, steps } => numeric_call("binary64Value", value, steps),
        Expr::Read { scope, path } => format!(
            "readValue({},[]string{{{}}})",
            matches!(scope, Scope::Item),
            path.iter().map(|s| quote(s)).collect::<Vec<_>>().join(",")
        ),
        Expr::Field { object, name } => {
            format!("fieldValue({},{})", expression(object), quote(name))
        }
        Expr::Record { fields } => record(fields),
        Expr::List { items } => format!("listValue([]expression{{{}}})", expressions(items)),
        Expr::Fallback {
            value,
            fallback,
            on_null,
        } => format!(
            "fallbackValue({},{},{on_null})",
            expression(value),
            expression(fallback)
        ),
        Expr::Choose {
            condition: test,
            then_value,
            else_value,
        } => format!(
            "chooseValue({},{},{})",
            condition(test),
            expression(then_value),
            expression(else_value)
        ),
        Expr::Arithmetic {
            operation,
            left,
            right,
            overflow,
        } => format!(
            "integerArithmetic({},{},{},{})",
            matches!(operation, IntegerOp::Multiply),
            matches!(overflow, Overflow::Wrap),
            expression(left),
            expression(right)
        ),
        Expr::Map { list, value } => {
            format!("mapItems({},{})", expression(list), expression(value))
        }
        Expr::DistinctCount {
            list,
            condition: test,
            key,
        } => format!(
            "countDistinct({},{},{})",
            expression(list),
            condition(test),
            expression(key)
        ),
        Expr::Concat { parts } => format!("concatText([]expression{{{}}})", expressions(parts)),
        Expr::Join { list, separator } => {
            format!("joinText({},{})", expression(list), expression(separator))
        }
        Expr::IntegerString { value } => format!("integerText({})", expression(value)),
        Expr::ConcatLists { lists } => {
            format!("concatLists([]expression{{{}}})", expressions(lists))
        }
        Expr::ItemIndex => "indexValue".to_owned(),
        Expr::SelectMap {
            list,
            condition: test,
            value,
        } => format!(
            "selectItems({},{},{},nil)",
            expression(list),
            condition(test),
            expression(value)
        ),
        Expr::Find {
            list,
            condition: test,
            value,
            otherwise,
        } => format!(
            "selectItems({},{},{},{})",
            expression(list),
            condition(test),
            expression(value),
            expression(otherwise)
        ),
        Expr::Binary64ToInteger {
            value,
            steps,
            out_of_range: Binary64Range::Reject,
        } => numeric_call("binary64Integer", value, steps),
    }
}

fn numeric_step(step: &Binary64Step) -> String {
    let (op, value) = match step {
        Binary64Step::Multiply { value } => ("multiply", value),
        Binary64Step::Minimum { value } => ("minimum", value),
        Binary64Step::Maximum { value } => ("maximum", value),
    };
    let bits = super::numeric::literal(value)
        .expect("checked literal")
        .to_bits();
    format!("{{op:{},value:floatBits(0x{bits:016x})}}", quote(op))
}

fn condition(test: &Condition) -> String {
    match test {
        Condition::Present { value } => format!("isPresent({})", expression(value)),
        Condition::Boolean { value } => format!("asBoolean({})", expression(value)),
        Condition::Equal { left, right } => {
            format!("equalValues({},{})", expression(left), expression(right))
        }
        Condition::Greater { left, right } => {
            format!("greaterThan({},{})", expression(left), expression(right))
        }
        Condition::StartsWith { value, prefix } => {
            format!("startsWith({},{})", expression(value), expression(prefix))
        }
        Condition::All { conditions } => format!(
            "allOf([]condition{{{}}})",
            conditions
                .iter()
                .map(condition)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Condition::Any { conditions } => format!(
            "anyOf([]condition{{{}}})",
            conditions
                .iter()
                .map(condition)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Condition::Not { condition: test } => format!("negate({})", condition(test)),
    }
}

fn runtime_sources(
    positional: bool,
    floating: bool,
    capture: bool,
) -> [(&'static str, &'static str); 6] {
    [
        (
            "runtime.go",
            if positional {
                include_str!("go_runtime.go.txt")
            } else if floating {
                include_str!("legacy_v5/go_runtime.go.txt")
            } else if capture {
                include_str!("legacy_v4/go_runtime.go.txt")
            } else {
                include_str!("legacy_v1_v3/go_runtime.go.txt")
            },
        ),
        (
            "input.go",
            if positional {
                include_str!("go_input.go.txt")
            } else if capture {
                include_str!("legacy_v4_v5/go_input.go.txt")
            } else {
                include_str!("legacy_v1_v3/go_input.go.txt")
            },
        ),
        (
            "expression.go",
            if positional {
                include_str!("go_expression.go.txt")
            } else {
                include_str!("legacy_v1_v5/go_expression.go.txt")
            },
        ),
        ("collection.go", include_str!("go_collection.go.txt")),
        (
            "condition.go",
            if floating {
                include_str!("go_condition.go.txt")
            } else {
                include_str!("legacy_v1_v4/go_condition.go.txt")
            },
        ),
        (
            "numeric.go",
            if floating {
                include_str!("go_numeric.go.txt")
            } else {
                include_str!("legacy_v1_v4/go_numeric.go.txt")
            },
        ),
    ]
}

fn floating_literal(value: &str) -> String {
    format!(
        "literal(floatBits({}))",
        super::numeric::literal(value)
            .expect("checked literal")
            .to_bits()
    )
}
fn numeric_call(name: &str, value: &Expr, steps: &[Binary64Step]) -> String {
    format!(
        "{name}({},[]numericStep{{{}}})",
        expression(value),
        steps.iter().map(numeric_step).collect::<Vec<_>>().join(",")
    )
}
