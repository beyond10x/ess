// Deliberately bounded npm identities, including one optional scope. No path or
// expression is built from this name. The limit includes the scope and slash.
fn package_name(package: &str) -> bool {
    fn part(part: &str) -> bool {
        !part.is_empty()
            && part.as_bytes()[0].is_ascii_lowercase()
            && part
                .bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || b"-_.".contains(&c))
    }
    if package.len() > 214 {
        return false;
    }
    if let Some(scoped) = package.strip_prefix('@') {
        scoped
            .split_once('/')
            .is_some_and(|(scope, name)| part(scope) && part(name))
    } else {
        part(package)
    }
}

pub(super) fn generate(plan: &Plan, package: &str) -> Result<Realization, Refused> {
    if !package_name(package) {
        return Err(Refused(vec![finding("/", "typescript_package",
            "use a lowercase npm name or @scope/name, each part starting with a-z and continuing with a-z, 0-9, -, _ or .; at most 214 bytes")]));
    }
    typescript_schema::qualify(plan)?;
    let (roots, mut files) = target::sources(plan)?;
    let mut schemas = "// Code generated by ESS. DO NOT EDIT.\nimport { fromBits } from './numeric.js';\nimport type { Value } from './value.js';\nimport type { Schema, RootSchema } from './schema.js';\n\nexport const roots: readonly RootSchema[] = [\n".to_owned();
    for root in &roots {
        let document: Value =
            serde_json::from_str(&files[&root.schema_path]).expect("generated schema JSON");
        writeln!(schemas, "  {},", typescript_schema::root_binding(&document))
            .expect("String write");
    }
    schemas.push_str("];\n");
    files.insert("src/schemas.ts".to_owned(), schemas);
    files.insert("src/bindings.ts".to_owned(), bindings(plan, &roots));
    files.extend(runtime_sources());
    files.insert("source.recipe.json".to_owned(), plan.to_json());
    files.insert(
        "schema-profile.json".to_owned(),
        typescript_schema::profile(),
    );
    files.insert(
        "package.json".to_owned(),
        pretty(&json!({
            "name":package,"version":"0.0.0","private":true,"type":"module",
            "exports":{".":{"types":"./dist/index.d.ts","import":"./dist/index.js"}},
            "types":"./dist/index.d.ts","scripts":{"build":"tsc --project tsconfig.json"}
        })),
    );
    files.insert(
        "tsconfig.json".to_owned(),
        pretty(&json!({"compilerOptions":{
        "target":"ES2022","module":"NodeNext","moduleResolution":"NodeNext","strict":true,
        "noUncheckedIndexedAccess":true,"exactOptionalPropertyTypes":true,
        "declaration":true,"outDir":"dist","rootDir":"src","lib":["ES2022","DOM"]
    },"include":["src/**/*.ts"]})),
    );
    files.insert("README.md".to_owned(), format!(
        "# {package}\n\nGenerated standalone ES2022 normalization. Compile with TypeScript 6.0.3 (`tsc --project tsconfig.json`); Node 22.23.1 is the qualified runtime. Generation installs nothing. No runtime dependencies are required.\n\nImport `Normalizer` from this package. `new Normalizer().normalize(branch, jsonText)` returns `{{ok:true,json}}` or `{{ok:false,findings}}`. `normalizeBase64Json(branch, encoded)` accepts canonical standard base64 containing UTF-8 JSON text. Inputs and successful outputs are complete JSON texts; no decoded-object API or implicit numeric coercion is provided.\n\nThe fixed `schema-profile.json` lists the qualified constraints. Formats are annotations, defaults do not execute, and unsupported constraints (including uniqueItems:true) refuse during generation. Private runtime files, source pins and the profile are hashed in `normalization-report.json`; compiled dist is a consumer build product. Internal modules are not package exports.\n"
    ));
    Ok(target::finish(
        plan,
        target::Configuration::Typescript {
            package: package.to_owned(),
        },
        files,
        roots,
    ))
}

fn bindings(plan: &Plan, roots: &[target::SchemaIdentity]) -> String {
    let mut bindings = "// Code generated by ESS. DO NOT EDIT.\nimport * as e from './expression.js';\nimport * as c from './collection.js';\nimport * as p from './condition.js';\nimport { fromBits } from './numeric.js';\nimport type { Stage } from './expression.js';\nimport type { Policies } from './input.js';\n\nexport const branches: ReadonlyMap<string, readonly Stage[]> = new Map([\n".to_owned();
    for (name, stages) in &plan.recipe.branches {
        writeln!(bindings, "[{},[", quote(name)).expect("String write");
        for stage in stages {
            let input = roots
                .iter()
                .position(|root| root.identity == stage.input)
                .expect("checked root");
            let output = roots
                .iter()
                .position(|root| root.identity == stage.output)
                .expect("checked root");
            writeln!(
                bindings,
                "{{input:{input},output:{output},requires:[{}],value:{}}},",
                stage
                    .requires
                    .iter()
                    .map(condition)
                    .collect::<Vec<_>>()
                    .join(","),
                expression(&stage.value)
            )
            .expect("String write");
        }
        bindings.push_str("]],\n");
    }
    bindings
        .push_str("]);\n\nexport const positionArities: ReadonlyMap<string, bigint> = new Map([\n");
    for (at, arity) in &plan.position_arities {
        writeln!(bindings, "[{}, {arity}n],", quote(at)).expect("String write");
    }
    bindings.push_str("]);\n\nexport const policies: ReadonlyMap<string, Policies> = new Map([\n");
    for name in plan.recipe.branches.keys() {
        let numbers = input_paths(
            plan.recipe
                .binary64_inputs
                .as_ref()
                .and_then(|map| map.get(name)),
        );
        let captures = input_paths(
            plan.recipe
                .raw_json_inputs
                .as_ref()
                .and_then(|map| map.get(name)),
        );
        let positions = plan
            .recipe
            .positional_inputs
            .as_ref()
            .and_then(|map| map.get(name))
            .into_iter()
            .flatten()
            .map(|policy| {
                format!(
                    "{{path:{},length:{}}}",
                    input_path(&policy.path),
                    policy.length
                )
            })
            .collect::<Vec<_>>()
            .join(",");
        writeln!(
            bindings,
            "[{},{{numbers:{numbers},captures:{captures},positions:[{positions}]}}],",
            quote(name)
        )
        .expect("String write");
    }
    writeln!(
        bindings,
        "]);\n\nexport const binary64 = {};",
        [super::FORMAT_V5, super::FORMAT_V6].contains(&plan.recipe.format.as_str())
    )
    .expect("String write");
    bindings
}

fn pretty(value: &Value) -> String {
    format!(
        "{}\n",
        serde_json::to_string_pretty(value).expect("typed metadata serializes")
    )
}

fn runtime_sources() -> BTreeMap<String, String> {
    [
        ("index", include_str!("ts_runtime.ts.txt")),
        ("value", include_str!("ts_value.ts.txt")),
        ("numeric", include_str!("ts_numeric.ts.txt")),
        ("input", include_str!("ts_input.ts.txt")),
        ("retained", include_str!("ts_retained.ts.txt")),
        ("schema", include_str!("ts_schema.ts.txt")),
        ("expression", include_str!("ts_expression.ts.txt")),
        ("condition", include_str!("ts_condition.ts.txt")),
        ("collection", include_str!("ts_collection.ts.txt")),
    ]
    .into_iter()
    .map(|(name, source)| (format!("src/{name}.ts"), source.to_owned()))
    .collect()
}

fn input_path(path: &[NumberPath]) -> String {
    format!(
        "[{}]",
        path.iter()
            .map(|segment| match segment {
                NumberPath::Field { name } => quote(name),
                NumberPath::Items => "null".to_owned(),
            })
            .collect::<Vec<_>>()
            .join(",")
    )
}

fn input_paths(paths: Option<&Vec<Vec<NumberPath>>>) -> String {
    format!(
        "[{}]",
        paths
            .into_iter()
            .flatten()
            .map(|path| input_path(path))
            .collect::<Vec<_>>()
            .join(",")
    )
}

fn expressions(values: &[Expr]) -> String {
    values.iter().map(expression).collect::<Vec<_>>().join(",")
}

// Keep the sealed operation inventory in one exhaustive match.
#[allow(clippy::too_many_lines)]
fn expression(value: &Expr) -> String {
    match value {
        Expr::Position { value, index } => {
            format!("e.positionValue({},{index}n)", expression(value))
        }
        Expr::Null => "e.literal(null)".to_owned(),
        Expr::Boolean { value } => format!("e.literal({value})"),
        Expr::String { value } => format!("e.literal({})", quote(value)),
        Expr::Integer { value } => format!("e.literal({value}n)"),
        Expr::Binary64Literal { value } => format!("e.literal({})", floating_literal(value)),
        Expr::Binary64 { value, steps } => numeric_call(value, steps, false),
        Expr::Binary64ToInteger {
            value,
            steps,
            out_of_range: Binary64Range::Reject,
        } => numeric_call(value, steps, true),
        Expr::Read { scope, path } => format!(
            "e.readValue({},[{}])",
            matches!(scope, Scope::Item),
            path.iter()
                .map(|name| quote(name))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Expr::Field { object, name } => {
            format!("e.fieldValue({},{})", expression(object), quote(name))
        }
        Expr::Record { fields } => format!(
            "e.recordValue([{}])",
            fields
                .iter()
                .map(|(key, value)| format!("[{},{}]", quote(key), expression(value)))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Expr::List { items } => format!("e.listValue([{}])", expressions(items)),
        Expr::Fallback {
            value,
            fallback,
            on_null,
        } => format!(
            "e.fallbackValue({},{},{on_null})",
            expression(value),
            expression(fallback)
        ),
        Expr::Choose {
            condition: test,
            then_value,
            else_value,
        } => format!(
            "e.chooseValue({},{},{})",
            condition(test),
            expression(then_value),
            expression(else_value)
        ),
        Expr::Arithmetic {
            operation,
            left,
            right,
            overflow,
        } => format!(
            "e.integerArithmetic({},{},{},{})",
            matches!(operation, IntegerOp::Multiply),
            matches!(overflow, Overflow::Wrap),
            expression(left),
            expression(right)
        ),
        Expr::Map { list, value } => {
            format!("c.mapItems({},{})", expression(list), expression(value))
        }
        Expr::DistinctCount {
            list,
            condition: test,
            key,
        } => format!(
            "c.countDistinct({},{},{})",
            expression(list),
            condition(test),
            expression(key)
        ),
        Expr::Concat { parts } => format!("e.concatText([{}])", expressions(parts)),
        Expr::Join { list, separator } => {
            format!("e.joinText({},{})", expression(list), expression(separator))
        }
        Expr::IntegerString { value } => format!("e.integerText({})", expression(value)),
        Expr::ConcatLists { lists } => format!("c.concatLists([{}])", expressions(lists)),
        Expr::ItemIndex => "c.indexValue".to_owned(),
        Expr::SelectMap {
            list,
            condition: test,
            value,
        } => format!(
            "c.selectItems({},{},{})",
            expression(list),
            condition(test),
            expression(value)
        ),
        Expr::Find {
            list,
            condition: test,
            value,
            otherwise,
        } => format!(
            "c.selectItems({},{},{},{})",
            expression(list),
            condition(test),
            expression(value),
            expression(otherwise)
        ),
    }
}

fn floating_literal(token: &str) -> String {
    format!(
        "fromBits(0x{:016x}n)",
        super::numeric::literal(token)
            .expect("checked literal")
            .to_bits()
    )
}

fn numeric_call(value: &Expr, steps: &[Binary64Step], truncate: bool) -> String {
    let steps = steps
        .iter()
        .map(|step| {
            let (op, token) = match step {
                Binary64Step::Multiply { value } => ("multiply", value),
                Binary64Step::Minimum { value } => ("minimum", value),
                Binary64Step::Maximum { value } => ("maximum", value),
            };
            format!("[{},{}]", quote(op), floating_literal(token))
        })
        .collect::<Vec<_>>()
        .join(",");
    format!(
        "e.binary64Value({},[{steps}],{truncate})",
        expression(value)
    )
}

fn condition(test: &Condition) -> String {
    match test {
        Condition::Present { value } => format!("p.isPresent({})", expression(value)),
        Condition::Boolean { value } => format!("p.asBoolean({})", expression(value)),
        Condition::Equal { left, right } => {
            format!("p.equalValues({},{})", expression(left), expression(right))
        }
        Condition::Greater { left, right } => {
            format!("p.greaterThan({},{})", expression(left), expression(right))
        }
        Condition::StartsWith { value, prefix } => {
            format!("p.startsWith({},{})", expression(value), expression(prefix))
        }
        Condition::All { conditions } => format!(
            "p.allOf([{}])",
            conditions
                .iter()
                .map(condition)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Condition::Any { conditions } => format!(
            "p.anyOf([{}])",
            conditions
                .iter()
                .map(condition)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Condition::Not { condition: test } => format!("p.negate({})", condition(test)),
    }
}
