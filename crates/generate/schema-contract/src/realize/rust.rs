/// Whether `node` can hold a JSON number at any depth, references followed: a `Number`, an
/// `Integer`, a native-width integer or unrestricted JSON (beyond10x/ess#483).
fn holds_number(plan: &Plan, node: &Node) -> bool {
    let mut pending = vec![node];
    let mut followed = BTreeSet::new();
    while let Some(node) = pending.pop() {
        match &node.shape {
            Shape::Json | Shape::Number | Shape::Integer | Shape::SizedInteger(_) => return true,
            Shape::Ref(name) => {
                if followed.insert(name) {
                    pending.push(&plan.definitions[name]);
                }
            }
            _ => pending.extend(children(node)),
        }
    }
    false
}

fn field_name(wire: &str) -> String {
    let mut result = String::new();
    let mut lower = false;
    for c in wire.chars() {
        if !c.is_ascii_alphanumeric() && c != '_' {
            if !result.ends_with('_') {
                result.push('_');
            }
            lower = false;
        } else {
            if c.is_ascii_uppercase() && lower {
                result.push('_');
            }
            result.push(c.to_ascii_lowercase());
            lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        }
    }
    let name = result.trim_matches('_');
    match name {
        "self" | "super" | "crate" => format!("{name}_value"),
        "as" | "async" | "await" | "break" | "const" | "continue" | "dyn" | "else" | "enum"
        | "extern" | "false" | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match"
        | "mod" | "move" | "mut" | "pub" | "ref" | "return" | "static" | "struct" | "trait"
        | "true" | "type" | "unsafe" | "use" | "where" | "while" | "abstract" | "become"
        | "box" | "do" | "final" | "macro" | "override" | "priv" | "typeof" | "unsized"
        | "virtual" | "yield" | "try" | "gen" => format!("r#{name}"),
        _ => name.to_owned(),
    }
}

pub(super) fn package_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name.as_bytes()[0].is_ascii_lowercase()
        && name
            .bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_' || c == b'-')
        && ![
            "self",
            "super",
            "crate",
            "std",
            "core",
            "alloc",
            "serde",
            "serde_json",
        ]
        .contains(&name)
}

/// One accessor per typed variant attribute of the enum `name` (`ess/23`, beyond10x/ess#450),
/// answering each variant's value: `bool`, `i64`, or the text — a `Decimal` as its decimal string —
/// and `Option` of these where a variant may leave the attribute unfilled. `variants` pairs each
/// wire spelling with the variant it names.
fn accessors(
    output: &mut String,
    name: &str,
    variants: &[(String, String)],
    attributes: &[super::EnumAttribute],
) {
    writeln!(output, "\nimpl {name} {{").expect("String write");
    for attribute in attributes {
        let ty = match attribute.kind.as_str() {
            "boolean" => "bool",
            "integer" => "i64",
            _ => "&'static str",
        };
        let ty = if attribute.optional {
            format!("Option<{ty}>")
        } else {
            ty.to_owned()
        };
        writeln!(
            output,
            "    /// The `{}` each variant declares.\n    pub fn {}(&self) -> {ty} {{\n        match self {{",
            attribute.name,
            field_name(&attribute.name)
        )
        .expect("String write");
        for (wire, variant) in variants {
            let value = attribute.values.get(wire).map(|value| match value {
                serde_json::Value::String(text) => format!("{text:?}"),
                other => other.to_string(),
            });
            let value = match (value, attribute.optional) {
                (Some(value), true) => format!("Some({value})"),
                (None, _) => "None".to_owned(),
                (Some(value), false) => value,
            };
            writeln!(output, "            Self::{variant} => {value},").expect("String write");
        }
        output.push_str("        }\n    }\n");
    }
    output.push_str("}\n");
}

/// A string newtype `name` that its source schema at `pointer` constrains (beyond10x/ess#579):
/// serialized as the plain string, decoded only when every character is in its alphabet and its
/// length within its bounds, and refused otherwise with the pointer and the constraint it breaks.
fn checked_text(
    output: &mut String,
    derive: &str,
    name: &str,
    pointer: &str,
    constraint: &super::TextConstraint,
) {
    let mut checks = Vec::new();
    if let Some(alphabet) = &constraint.alphabet {
        checks.push((
            format!("!self.0.chars().all(|c| {alphabet:?}.contains(c))"),
            format!("a value whose every character is one of `{alphabet}`"),
        ));
    }
    let count = "<i64 as ::std::convert::TryFrom<usize>>::try_from(self.0.chars().count()).unwrap_or(i64::MAX)";
    if let Some(minimum) = constraint.minimum {
        checks.push((
            format!("{count} < {minimum}"),
            format!("a value at least {minimum} characters long"),
        ));
    }
    if let Some(maximum) = constraint.maximum {
        checks.push((
            format!("{count} > {maximum}"),
            format!("a value at most {maximum} characters long"),
        ));
    }
    writeln!(output, "{derive}#[serde(transparent)]\npub struct {name}(pub ::std::string::String);\n\nimpl {name} {{\n    /// The first constraint the source schema declares that this value breaks (its alphabet,\n    /// then its length) as what a decoder expected instead, or `None` when it breaks none.\n    pub fn broken_constraint(&self) -> Option<&'static str> {{").expect("String write");
    for (check, expected) in &checks {
        writeln!(
            output,
            "        if {check} {{\n            return Some({expected:?});\n        }}"
        )
        .expect("String write");
    }
    writeln!(output, "        None\n    }}\n}}\n\nimpl<'de> ::serde::Deserialize<'de> for {name} {{\n    fn deserialize<D: ::serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{\n        let value = Self(<::std::string::String as ::serde::Deserialize>::deserialize(deserializer)?);\n        match value.broken_constraint() {{\n            Some(expected) => Err(::serde::de::Error::custom(::std::format_args!(\"{}: expected {{expected}}\"))),\n            None => Ok(value),\n        }}\n    }}\n}}", pointer.escape_debug().to_string().replace('{', "{{").replace('}', "}}")).expect("String write");
}

/// The trait codecs of a struct `name` with a shorthand (`ess/27`, beyond10x/ess#594), whose
/// derived record codecs are its inherent `serialize` and `deserialize` (`serde(remote = "Self")`).
/// It encodes the record. It decodes the record from a JSON object and, from the short form's
/// scalar, the struct with only `short`'s field filled, through one `deserialize_any`: nothing is
/// buffered, so raw-token fields of the record decode as they do without a shorthand.
fn short_form(
    out: &mut String,
    name: &str,
    fields: &[&String],
    short: &Shorthand,
    ty: &str,
    closed: bool,
) {
    let mut filled = String::new();
    for &wire in fields {
        let field = field_name(wire);
        if *wire == short.wire {
            write!(
                filled,
                " {field}: <{ty} as ::serde::Deserialize>::deserialize(deserializer)?,"
            )
            .expect("String write");
        } else {
            write!(filled, " {field}: ::std::default::Default::default(),").expect("String write");
        }
    }
    if !closed {
        filled.push_str(" ess_extra: ::std::default::Default::default(),");
    }
    let (method, value) = match short.kind {
        ShortKind::Boolean => ("visit_bool", "bool"),
        // Numbers are refused before this is written (`rust_shorthand_number`).
        ShortKind::String | ShortKind::Number => ("visit_str", "&str"),
    };
    let expecting = format!(
        "the `{}` value alone or the {name} record",
        short.wire.escape_debug()
    );
    writeln!(
        out,
        "impl ::serde::Serialize for {name} {{
    fn serialize<S: ::serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {{
        {name}::serialize(self, serializer)
    }}
}}

impl {name} {{
    /// The struct its short form writes: the shorthand field alone.
    fn ess_short_form<'de, D: ::serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{
        Ok(Self {{{filled} }})
    }}
}}

impl<'de> ::serde::Deserialize<'de> for {name} {{
    fn deserialize<D: ::serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{
        struct EssShortOrRecord;
        impl<'de> ::serde::de::Visitor<'de> for EssShortOrRecord {{
            type Value = {name};
            fn expecting(&self, formatter: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {{
                formatter.write_str({expecting:?})
            }}
            fn {method}<E: ::serde::de::Error>(self, value: {value}) -> Result<{name}, E> {{
                {name}::ess_short_form(::serde::de::IntoDeserializer::<E>::into_deserializer(value))
            }}
            fn visit_map<A: ::serde::de::MapAccess<'de>>(self, map: A) -> Result<{name}, A::Error> {{
                {name}::deserialize(::serde::de::value::MapAccessDeserializer::new(map))
            }}
        }}
        ::serde::Deserializer::deserialize_any(deserializer, EssShortOrRecord)
    }}
}}"
    )
    .expect("String write");
}
