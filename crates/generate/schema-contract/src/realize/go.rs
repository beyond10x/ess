//! Go data records with standard-library codecs and explicit presence and nullability.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use super::native::{nullable, string_values};
use super::{
    children, declaration_name, finding, Field, Finding, Node, Plan, Realization, Refused, Report,
    Shape, TargetConfiguration, UnionMode,
};

const HELPERS: &str = include_str!("go_support.go.txt");

pub(super) fn emit(plan: &Plan, package: &str, module: &str) -> Result<Realization, Refused> {
    if !package_name(package) || !module_name(module) {
        return Err(Refused(vec![finding("/", "go_identity", "use a non-keyword lowercase Go package name and an ASCII module path without empty, dot or traversal segments")]));
    }
    let mut emitter = Emitter {
        plan,
        output: BTreeMap::new(),
        allocated: plan.names.values().cloned().collect(),
        anonymous: BTreeMap::new(),
        errors: BTreeSet::new(),
        report: plan.report(TargetConfiguration::Go {
            package: package.to_owned(),
            module: module.to_owned(),
        }),
    };
    for helper in [
        "EssJSON",
        "EssNumber",
        "EssNull",
        "EssNever",
        "EssPresence",
        "EssNullable",
    ] {
        if !emitter.allocated.insert(helper.to_owned()) {
            emitter
                .errors
                .insert(finding("/", "go_helper_collision", helper));
        }
    }
    if !plan.binary64.is_empty() {
        for helper in ["EssBinary64", "NewEssBinary64"] {
            if !emitter.allocated.insert(helper.to_owned()) {
                emitter
                    .errors
                    .insert(finding("/", "go_helper_collision", helper));
            }
        }
    }
    for (name, node) in &plan.definitions {
        emitter.account(node);
        emitter.named(&plan.names[name], node);
    }
    if !emitter.errors.is_empty() {
        return Err(Refused(emitter.errors.into_iter().collect()));
    }
    let imports = if plan.binary64.is_empty() {
        ""
    } else {
        "import (\n\t\"math\"\n\t\"strconv\"\n\t\"strings\"\n)\n\n"
    };
    let mut output = format!("// Code generated by ESS {}; DO NOT EDIT.\n// Source SHA-256: {}\n// {}\n// Structural serialization only; see types-report.json for runtime obligations.\n\npackage {package}\n\n{imports}{HELPERS}\n", env!("CARGO_PKG_VERSION"), plan.source_digest, plan.input_comment());
    if !plan.binary64.is_empty() {
        output.push_str(include_str!("go_binary64.go.txt"));
        output.push('\n');
    }
    for declaration in emitter.output.values() {
        output.push_str(declaration);
        output.push('\n');
    }
    Ok(Realization {
        declarations: output,
        report: emitter.report,
        supporting: BTreeMap::from([(
            "go.mod".to_owned(),
            format!("module {}\n\ngo 1.23.0\n", quote(module)),
        )]),
    })
}

struct Emitter<'a> {
    plan: &'a Plan,
    output: BTreeMap<String, String>,
    allocated: BTreeSet<String>,
    anonymous: BTreeMap<String, String>,
    errors: BTreeSet<Finding>,
    report: Report,
}

impl Emitter<'_> {
    fn account(&mut self, node: &Node) {
        match &node.shape {
            Shape::Integer => {
                self.report.obligations.insert(finding(&node.pointer, "integer", "EssNumber preserves exact JSON numeric tokens but integrality remains a source-schema validation obligation"));
            }
            Shape::Union { mode, .. } => {
                if matches!(mode, UnionMode::OneOf) {
                    self.report.obligations.insert(finding(
                        &node.pointer,
                        "oneOf",
                        "validate exclusive source branch membership",
                    ));
                }
                if matches!(mode, UnionMode::AnyOf | UnionMode::OneOf) {
                    self.report.obligations.insert(finding(&node.pointer, "untagged_selection", "native unions select the first structurally decodable alternative, not source-constraint validation or external dispatch"));
                }
            }
            _ => {}
        }
        for child in children(node) {
            self.account(child);
        }
    }

    fn named(&mut self, name: &str, node: &Node) {
        let mut out = format!("// Source: {}\n", quote(&node.pointer));
        if !matches!(node.shape, Shape::Ref(_)) {
            if let Some(values) = string_values(node, self.plan, &mut BTreeSet::new()) {
                self.enumeration(&mut out, name, &values, &node.pointer);
                self.output.insert(name.to_owned(), out);
                return;
            }
        }
        match &node.shape {
            Shape::Object { fields, additional } => {
                self.record(&mut out, name, fields, additional, &node.pointer);
            }
            Shape::Array {
                prefix,
                items,
                minimum,
                maximum,
            } => {
                if prefix.is_empty() {
                    self.array(&mut out, name, items);
                } else if *minimum == prefix.len() as u64 && *maximum == Some(*minimum) {
                    self.tuple(&mut out, name, prefix);
                } else {
                    self.errors.insert(finding(
                        &node.pointer,
                        "go_prefix_layout",
                        "Go currently requires an exact prefix tuple",
                    ));
                }
            }
            Shape::Union { variants, .. } if nullable(variants).is_none() => {
                self.union(&mut out, name, variants, &node.pointer);
            }
            Shape::Intersection(_) | Shape::Literal(_) => {
                self.errors.insert(finding(
                    &node.pointer,
                    "go_intersection_or_literal",
                    "this native intersection or non-string literal needs an explicit Go mapping",
                ));
            }
            _ => {
                let ty = self.ty(node);
                let null = allows_null(node, self.plan, &mut BTreeSet::new());
                writeln!(out, "type {name} struct {{\n\tValue {ty}\n}}\n\nfunc (v {name}) MarshalJSON() ([]byte, error) {{\n\treturn essEncode(v.Value, {null})\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{\n\tvar decoded {ty}\n\tif err := essDecode(data, &decoded, {null}); err != nil {{\n\t\treturn err\n\t}}\n\tv.Value = decoded\n\treturn nil\n}}").expect("String write");
            }
        }
        self.output.insert(name.to_owned(), out);
    }

    fn enumeration(
        &mut self,
        out: &mut String,
        name: &str,
        values: &BTreeSet<String>,
        pointer: &str,
    ) {
        writeln!(out, "type {name} string\n").expect("String write");
        if !values.is_empty() {
            out.push_str("const (\n");
            for (index, value) in values.iter().enumerate() {
                let variant = format!("{name}V{index}");
                self.allocate(&variant, pointer);
                writeln!(out, "\t{variant} {name} = {}", quote(value)).expect("String write");
            }
            out.push_str(")\n\n");
        }
        writeln!(out, "func (v {name}) MarshalJSON() ([]byte, error) {{").expect("String write");
        if !values.is_empty() {
            let values = values
                .iter()
                .map(|value| quote(value))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "\tswitch string(v) {{\n\tcase {values}:\n\t\treturn json.Marshal(string(v))\n\t}}"
            )
            .expect("String write");
        }
        writeln!(out, "\treturn nil, fmt.Errorf(\"value is not a declared string literal\")\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{\n\tvar decoded string\n\tif err := essDecode(data, &decoded, false); err != nil {{\n\t\treturn err\n\t}}\n\tvalue := {name}(decoded)\n\tif _, err := value.MarshalJSON(); err != nil {{\n\t\treturn err\n\t}}\n\t*v = value\n\treturn nil\n}}").expect("String write");
    }

    fn record(
        &mut self,
        out: &mut String,
        name: &str,
        fields: &BTreeMap<String, Field>,
        additional: &Node,
        pointer: &str,
    ) {
        let closed = matches!(additional.shape, Shape::Never);
        let extra = if closed {
            None
        } else {
            Some(self.ty(additional))
        };
        let mut allocated = BTreeSet::from(["MarshalJSON".to_owned(), "UnmarshalJSON".to_owned()]);
        if !closed {
            allocated.insert("EssExtra".to_owned());
        }
        writeln!(out, "type {name} struct {{").expect("String write");
        for (wire, field) in fields {
            let id = declaration_name(wire);
            if id.is_empty() || id.as_bytes()[0].is_ascii_digit() || !allocated.insert(id.clone()) {
                self.errors.insert(finding(
                    &field.value.pointer,
                    "go_field_collision",
                    "invalid field identifier or collision after Go normalization",
                ));
            }
            let ty = self.ty(&field.value);
            let ty = if field.required {
                ty
            } else {
                format!("EssPresence[{ty}]")
            };
            writeln!(out, "\t{id} {ty}").expect("String write");
        }
        if let Some(extra) = &extra {
            writeln!(out, "\tEssExtra map[string]{extra}").expect("String write");
        }
        writeln!(out, "}}\n\nfunc (v {name}) MarshalJSON() ([]byte, error) {{\n\tobject := make(map[string]json.RawMessage)").expect("String write");
        for (wire, field) in fields {
            self.encode_field(out, wire, field);
        }
        if extra.is_some() {
            out.push_str("\tfor key, value := range v.EssExtra {\n");
            if !fields.is_empty() {
                let keys = fields
                    .keys()
                    .map(|key| quote(key))
                    .collect::<Vec<_>>()
                    .join(", ");
                writeln!(out, "\t\tswitch key {{\n\t\tcase {keys}:\n\t\t\treturn nil, fmt.Errorf(\"additional key collides with a declared field\")\n\t\t}}").expect("String write");
            }
            let null = allows_null(additional, self.plan, &mut BTreeSet::new());
            writeln!(out, "\t\tencoded, err := essEncode(value, {null})\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tobject[key] = encoded\n\t}}").expect("String write");
        }
        writeln!(out, "\treturn json.Marshal(object)\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{\n\tvar object map[string]json.RawMessage\n\tif err := essDecode(data, &object, false); err != nil {{\n\t\treturn err\n\t}}\n\tvar decoded {name}").expect("String write");
        for (wire, field) in fields {
            self.decode_field(out, wire, field);
        }
        if let Some(extra) = extra {
            let null = allows_null(additional, self.plan, &mut BTreeSet::new());
            writeln!(out, "\tdecoded.EssExtra = make(map[string]{extra}, len(object))\n\tfor key, raw := range object {{\n\t\tvar value {extra}\n\t\tif err := essDecode(raw, &value, {null}); err != nil {{\n\t\t\treturn err\n\t\t}}\n\t\tdecoded.EssExtra[key] = value\n\t}}").expect("String write");
            self.report.obligations.insert(finding(pointer, "open_object_storage", "preserve EssExtra during transformations; serialization rejects declared-key collisions"));
        } else {
            out.push_str("\tif len(object) != 0 {\n\t\treturn fmt.Errorf(\"undeclared object fields\")\n\t}\n");
        }
        out.push_str("\t*v = decoded\n\treturn nil\n}\n");
    }

    fn encode_field(&self, out: &mut String, wire: &str, field: &Field) {
        let id = declaration_name(wire);
        let null = allows_null(&field.value, self.plan, &mut BTreeSet::new());
        let value = if field.required {
            format!("v.{id}")
        } else {
            format!("v.{id}.Value")
        };
        if field.required {
            out.push_str("\t{\n");
        } else {
            writeln!(out, "\tif v.{id}.Present {{").expect("String write");
        }
        writeln!(out, "\t\tencoded, err := essEncode({value}, {null})\n\t\tif err != nil {{\n\t\t\treturn nil, fmt.Errorf(\"field %s: %w\", {}, err)\n\t\t}}\n\t\tobject[{}] = encoded\n\t}}", quote(wire), quote(wire)).expect("String write");
    }

    fn decode_field(&self, out: &mut String, wire: &str, field: &Field) {
        let id = declaration_name(wire);
        let target = if field.required {
            format!("decoded.{id}")
        } else {
            format!("decoded.{id}.Value")
        };
        let null = allows_null(&field.value, self.plan, &mut BTreeSet::new());
        writeln!(out, "\tif raw, exists := object[{}]; exists {{\n\t\tif err := essDecode(raw, &{target}, {null}); err != nil {{\n\t\t\treturn fmt.Errorf(\"field %s: %w\", {}, err)\n\t\t}}", quote(wire), quote(wire)).expect("String write");
        if !field.required {
            writeln!(out, "\t\tdecoded.{id}.Present = true").expect("String write");
        }
        if field.required {
            writeln!(
                out,
                "\t}} else {{\n\t\treturn fmt.Errorf(\"missing required field %s\", {})",
                quote(wire)
            )
            .expect("String write");
        }
        writeln!(out, "\t}}\n\tdelete(object, {})", quote(wire)).expect("String write");
    }

    fn array(&mut self, out: &mut String, name: &str, items: &Node) {
        let ty = self.ty(items);
        let null = allows_null(items, self.plan, &mut BTreeSet::new());
        writeln!(out, "type {name} []{ty}\n\nfunc (v {name}) MarshalJSON() ([]byte, error) {{\n\tarray := make([]json.RawMessage, len(v))\n\tfor index, value := range v {{\n\t\tencoded, err := essEncode(value, {null})\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tarray[index] = encoded\n\t}}\n\treturn json.Marshal(array)\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{\n\tvar array []json.RawMessage\n\tif err := essDecode(data, &array, false); err != nil {{\n\t\treturn err\n\t}}\n\tdecoded := make({name}, len(array))\n\tfor index, raw := range array {{\n\t\tif err := essDecode(raw, &decoded[index], {null}); err != nil {{\n\t\t\treturn err\n\t\t}}\n\t}}\n\t*v = decoded\n\treturn nil\n}}").expect("String write");
    }

    fn tuple(&mut self, out: &mut String, name: &str, prefix: &[Node]) {
        writeln!(out, "type {name} struct {{").expect("String write");
        for (index, item) in prefix.iter().enumerate() {
            writeln!(out, "\tItem{index} {}", self.ty(item)).expect("String write");
        }
        writeln!(out, "}}\n\nfunc (v {name}) MarshalJSON() ([]byte, error) {{\n\tarray := make([]json.RawMessage, {})", prefix.len()).expect("String write");
        for (index, item) in prefix.iter().enumerate() {
            let null = allows_null(item, self.plan, &mut BTreeSet::new());
            writeln!(out, "\t{{\n\t\tencoded, err := essEncode(v.Item{index}, {null})\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tarray[{index}] = encoded\n\t}}").expect("String write");
        }
        writeln!(out, "\treturn json.Marshal(array)\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{\n\tvar array []json.RawMessage\n\tif err := essDecode(data, &array, false); err != nil {{\n\t\treturn err\n\t}}\n\tif len(array) != {} {{\n\t\treturn fmt.Errorf(\"wrong prefix tuple length\")\n\t}}\n\tvar decoded {name}", prefix.len()).expect("String write");
        for (index, item) in prefix.iter().enumerate() {
            let null = allows_null(item, self.plan, &mut BTreeSet::new());
            writeln!(out, "\tif err := essDecode(array[{index}], &decoded.Item{index}, {null}); err != nil {{\n\t\treturn err\n\t}}").expect("String write");
        }
        out.push_str("\t*v = decoded\n\treturn nil\n}\n");
    }

    fn union(&mut self, out: &mut String, name: &str, variants: &[Node], pointer: &str) {
        let marker = format!("{name}Variant");
        self.allocate(&marker, pointer);
        writeln!(out, "type {name} struct {{\n\tValue {marker}\n}}\n\ntype {marker} interface {{\n\tess{name}Variant()\n\tjson.Marshaler\n}}\n").expect("String write");
        let types = variants
            .iter()
            .map(|variant| self.ty(variant))
            .collect::<Vec<_>>();
        for (index, ty) in types.iter().enumerate() {
            let variant = format!("{name}V{index}");
            self.allocate(&variant, &variants[index].pointer);
            let null = allows_null(&variants[index], self.plan, &mut BTreeSet::new());
            writeln!(out, "type {variant} struct {{\n\tValue {ty}\n}}\n\nfunc ({variant}) ess{name}Variant() {{}}\n\nfunc (v {variant}) MarshalJSON() ([]byte, error) {{\n\treturn essEncode(v.Value, {null})\n}}\n").expect("String write");
        }
        let null = variants
            .iter()
            .any(|variant| allows_null(variant, self.plan, &mut BTreeSet::new()));
        writeln!(out, "func (v {name}) MarshalJSON() ([]byte, error) {{\n\tif v.Value == nil {{\n\t\treturn nil, fmt.Errorf(\"no union alternative selected\")\n\t}}\n\treturn essEncode(v.Value, {null})\n}}\n\nfunc (v *{name}) UnmarshalJSON(data []byte) error {{").expect("String write");
        for (index, ty) in types.iter().enumerate() {
            let null = allows_null(&variants[index], self.plan, &mut BTreeSet::new());
            writeln!(out, "\t{{\n\t\tvar decoded {ty}\n\t\tif err := essDecode(data, &decoded, {null}); err == nil {{\n\t\t\tv.Value = {name}V{index}{{Value: decoded}}\n\t\t\treturn nil\n\t\t}}\n\t}}").expect("String write");
        }
        out.push_str("\treturn fmt.Errorf(\"no structurally decodable union alternative\")\n}\n");
    }

    fn ty(&mut self, node: &Node) -> String {
        if self.plan.binary64.contains(&node.pointer) {
            return "EssBinary64".to_owned();
        }
        match &node.shape {
            Shape::Json => "EssJSON".to_owned(),
            Shape::Never => "EssNever".to_owned(),
            Shape::Null => "EssNull".to_owned(),
            Shape::Boolean => "bool".to_owned(),
            Shape::String => "string".to_owned(),
            Shape::Number | Shape::Integer => "EssNumber".to_owned(),
            Shape::Ref(name) => format!("*{}", self.plan.names[name]),
            Shape::Union { variants, .. } if nullable(variants).is_some() => format!(
                "EssNullable[{}]",
                self.ty(nullable(variants).expect("nullable union"))
            ),
            _ => self.anonymous(node),
        }
    }

    fn anonymous(&mut self, node: &Node) -> String {
        let kind = match &node.shape {
            Shape::Object { .. } => "object",
            Shape::Array { .. } => "array",
            Shape::Union { .. } => "union",
            Shape::Intersection(_) => "intersection",
            Shape::Literal(_) => "literal",
            _ => "scalar",
        };
        let identity = format!("{}#{kind}", node.pointer);
        if let Some(name) = self.anonymous.get(&identity) {
            return name.clone();
        }
        let digest = crate::bundle::source_digest(&identity);
        let name = format!("EssShape{}", &digest[..16]);
        if !self.allocate(&name, &node.pointer) {
            return "EssNever".to_owned();
        }
        self.anonymous.insert(identity, name.clone());
        self.named(&name, node);
        name
    }

    fn allocate(&mut self, name: &str, pointer: &str) -> bool {
        if self.allocated.insert(name.to_owned()) {
            true
        } else {
            self.errors
                .insert(finding(pointer, "go_declaration_collision", name));
            false
        }
    }
}

fn allows_null(node: &Node, plan: &Plan, seen: &mut BTreeSet<String>) -> bool {
    match &node.shape {
        Shape::Json | Shape::Null => true,
        Shape::Ref(name) => {
            if !seen.insert(name.clone()) {
                return false;
            }
            let result = allows_null(&plan.definitions[name], plan, seen);
            seen.remove(name);
            result
        }
        Shape::Union { variants, .. } => variants
            .iter()
            .any(|variant| allows_null(variant, plan, seen)),
        Shape::Intersection(terms) => terms.iter().all(|term| allows_null(term, plan, seen)),
        _ => false,
    }
}

fn quote(text: &str) -> String {
    serde_json::to_string(text).expect("JSON string")
}

pub(super) fn package_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name.as_bytes()[0].is_ascii_lowercase()
        && name
            .bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_')
        && ![
            "break",
            "default",
            "func",
            "interface",
            "select",
            "case",
            "defer",
            "go",
            "map",
            "struct",
            "chan",
            "else",
            "goto",
            "package",
            "switch",
            "const",
            "fallthrough",
            "if",
            "range",
            "type",
            "continue",
            "for",
            "import",
            "return",
            "var",
        ]
        .contains(&name)
}

pub(super) fn module_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 256
        && name
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b".-_/".contains(&c))
        && name
            .split('/')
            .all(|part| !part.is_empty() && part != "." && part != ".." && !part.starts_with('.'))
}
